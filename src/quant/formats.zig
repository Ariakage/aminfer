    0, 1, 2, 3, 4, 6, 8, 12, 0, -1, -2, -3, -4, -6, -8, -12,
};

// ============================================================================
// Little-Endian & Float Helpers
// ============================================================================

inline fn readU16(bytes: []const u8, off: usize) u16 {
    return std.mem.readInt(u16, bytes[off..][0..2], .little);
}

inline fn readU32(bytes: []const u8, off: usize) u32 {
    return std.mem.readInt(u32, bytes[off..][0..4], .little);
}

inline fn readF16(bytes: []const u8, off: usize) f32 {
    return @floatCast(@as(f16, @bitCast(readU16(bytes, off))));
}

inline fn readF32(bytes: []const u8, off: usize) f32 {
    return @bitCast(readU32(bytes, off));
}

inline fn align4(v: usize) usize {
    return (v + 3) & ~@as(usize, 3);
}

inline fn getScaleMinK4(j: usize, q: []const u8) struct { sc: u8, m: u8 } {
    if (j < 4) {
        return .{ .sc = q[j] & 63, .m = q[j + 4] & 63 };
    }
    return .{
        .sc = (q[j + 4] & 0x0F) | ((q[j - 4] >> 6) << 4),
        .m = (q[j + 4] >> 4) | ((q[j] >> 6) << 4),
    };
}

