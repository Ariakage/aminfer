test "dequantRowCpuRef decodes all 23 GGUF block formats accurately" {
    // Q2_0 (64 weights / 18 B): d=0.5, codes=[0,1,2,3,...] -> [-0.5, 0, 0.5, 1.0]
    {
        var blk: [18]u8 = undefined;
        std.mem.writeInt(u16, blk[0..2], @bitCast(@as(f16, @floatCast(0.5))), .little);
        @memset(blk[2..18], 0xE4); // 0 | (1<<2) | (2<<4) | (3<<6) = 0xE4
        var out: [64]f32 = undefined;
        try dequantRowCpuRef(.gguf_q2_0, &blk, &.{}, 1, 64, 0, 64, &out);
        try std.testing.expectApproxEqAbs(@as(f32, -0.5), out[0], 1e-5);
        try std.testing.expectApproxEqAbs(@as(f32, 0.0), out[1], 1e-5);
        try std.testing.expectApproxEqAbs(@as(f32, 0.5), out[2], 1e-5);
        try std.testing.expectApproxEqAbs(@as(f32, 1.0), out[3], 1e-5);
    }

    // MXFP4 (32 weights / 17 B): e=128 (scale 2.0) -> 0.5 * 2.0 = 1.0; lo=2 (2), hi=10 (-2)
    {
        var blk: [17]u8 = undefined;
        blk[0] = 128;
        @memset(blk[1..17], 0xA2);
        var out: [32]f32 = undefined;
        try dequantRowCpuRef(.gguf_mxfp4, &blk, &.{}, 1, 32, 0, 32, &out);
        try std.testing.expectApproxEqAbs(@as(f32, 2.0), out[0], 1e-5);
        try std.testing.expectApproxEqAbs(@as(f32, -2.0), out[16], 1e-5);
    }

    // TQ2_0 (256 weights / 66 B): qs=0x00 (all -1), d=0.25 -> -0.25
    {
        var blk: [66]u8 = @splat(0);
        std.mem.writeInt(u16, blk[64..66], @bitCast(@as(f16, @floatCast(0.25))), .little);
        var out: [256]f32 = undefined;
        try dequantRowCpuRef(.gguf_tq2_0, &blk, &.{}, 1, 256, 0, 256, &out);
        for (out) |v| try std.testing.expectApproxEqAbs(@as(f32, -0.25), v, 1e-5);
    }

    // Smoke-test deterministic non-NaN decoding + gemvCpuRef across all 23 GGUF block dtypes (15..37).
    var buf: [256]u8 = undefined;
    for (&buf, 0..) |*b, idx| b.* = @intCast((idx * 37 + 13) & 0xFF);
    var x: [256]f16 = undefined;
    for (&x, 0..) |*v, idx| v.* = @floatCast(@as(f32, @floatFromInt(@as(i32, @intCast(idx % 9)) - 4)) * 0.25);

    var dtype_val: u8 = @backingInt(DType.gguf_q4_0);
    while (dtype_val <= @backingInt(DType.gguf_q2_0)) : (dtype_val += 1) {
        const dt: DType = @fromBackingInt(@intCast(dtype_val));
        const info = ggufBlockInfo(dt).?;
        // Force valid finite f16 scales in header/trailer bytes.
        var blk_buf: [256]u8 = buf;
        const one_f16: u16 = @bitCast(@as(f16, @floatCast(0.5)));
        switch (dt) {
            .gguf_q2_k => {
                std.mem.writeInt(u16, blk_buf[80..82], one_f16, .little);
                std.mem.writeInt(u16, blk_buf[82..84], one_f16, .little);
            },
            .gguf_q3_k => std.mem.writeInt(u16, blk_buf[108..110], one_f16, .little),
            .gguf_q6_k => std.mem.writeInt(u16, blk_buf[208..210], one_f16, .little),
            .gguf_tq1_0 => std.mem.writeInt(u16, blk_buf[52..54], one_f16, .little),
            .gguf_tq2_0 => std.mem.writeInt(u16, blk_buf[64..66], one_f16, .little),
            .gguf_iq1_m => {
                // Ensure reconstructed f16 scale bits are finite (clear bit 15..12 exponent all-ones).
                blk_buf[49] &= 0x7F;
                blk_buf[51] &= 0x7F;
                blk_buf[53] &= 0x7F;
                blk_buf[55] &= 0x7F;
            },
            .gguf_mxfp4 => blk_buf[0] = 127,
            .gguf_q4_1, .gguf_q5_1, .gguf_q4_k, .gguf_q5_k => {
                std.mem.writeInt(u16, blk_buf[0..2], one_f16, .little);
                std.mem.writeInt(u16, blk_buf[2..4], one_f16, .little);
            },
            else => std.mem.writeInt(u16, blk_buf[0..2], one_f16, .little),
        }
        var out_row: [256]f32 = undefined;
        try dequantRowCpuRef(dt, blk_buf[0..info.block_bytes], &.{}, 1, info.block_elems, 0, info.block_elems, out_row[0..info.block_elems]);
        var y: [1]f32 = undefined;
        try gemvCpuRef(dt, x[0..info.block_elems], blk_buf[0..info.block_bytes], &.{}, 1, info.block_elems, info.block_elems, &y);
        try std.testing.expect(std.math.isFinite(y[0]));
    }
}

test "actQuantEmulateCpuRef verifies all G24 modes including fouroversix MAE selection" {
    var x: [128]f16 = undefined;
    for (&x, 0..) |*v, idx| {
        // First 16 values fit cleanly within [-4, 4] except mild rounding; next blocks vary.
        const val: f32 = if (idx < 16)
            @as(f32, @floatFromInt(@as(i32, @intCast(idx)) - 8)) * 0.35
        else
            @as(f32, @floatFromInt(@as(i32, @intCast(idx % 17)) - 8)) * 0.5;
        v.* = @floatCast(val);
    }
    var out: [128]f16 = undefined;

    try actQuantEmulateCpuRef(.none, &x, 1, 128, &out);
    for (x, out) |a, b| try std.testing.expectEqual(a, b);

    inline for (.{
        ActQuantMode.mxfp8_g32,
        ActQuantMode.fp8_g128,
        ActQuantMode.nvfp4_g16,
        ActQuantMode.nvfp4_fouroversix_mae,
    }) |mode| {
        try actQuantEmulateCpuRef(mode, &x, 1, 128, &out);
        for (out) |v| try std.testing.expect(std.math.isFinite(@as(f32, @floatCast(v))));
    }

    // Verify FourOverSix MAE achieves <= MAE of static-6 nvfp4_g16 on every 16-element block.
    var x_f32: [16]f32 = .{ 0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0, -0.5, -1.0, -1.5, -2.0, -2.5, -3.0, -3.5, 4.0 };
    var out_6: [16]f32 = undefined;
    var out_46: [16]f32 = undefined;
    try actQuantEmulateF32CpuRef(.nvfp4_g16, &x_f32, 1, 16, &out_6);
    try actQuantEmulateF32CpuRef(.nvfp4_fouroversix_mae, &x_f32, 1, 16, &out_46);
    var err6: f32 = 0.0;
    var err46: f32 = 0.0;
    for (x_f32, 0..) |xv, i| {
        err6 += @abs(xv - out_6[i]);
        err46 += @abs(xv - out_46[i]);
    }
    try std.testing.expect(err46 <= err6 + 1e-6);
}
