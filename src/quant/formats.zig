/// Decodes OCP FP8 `E4M3FN` (`S.E4.M3`, bias = 7, NaN = `0x7F` / `0xFF`) to `f32`.
pub fn e4m3ToF32(bits: u8) f32 {
    const ax: u8 = bits & 0x7F;
    if (ax == 0x7F) return std.math.nan(f32);
    const exp: u32 = (ax >> 3) & 0x0F;
    const man: u32 = ax & 0x07;
    const mag: f32 = if (exp == 0)
        @as(f32, @floatFromInt(man)) * (1.0 / 512.0)
    else
        @bitCast(((exp + 120) << 23) | (man << 20));
    const mag_bits: u32 = @bitCast(mag);
    return @bitCast(mag_bits | (@as(u32, bits & 0x80) << 24));
}

/// Saturating RNE conversion from `f32` to OCP FP8 `E4M3FN` (`S.E4.M3`).
pub fn f32ToE4m3(val: f32) u8 {
    const sign: u8 = if (std.math.signbit(val)) 0x80 else 0;
    if (std.math.isNan(val)) return 0x7F;
    const ax: f32 = @abs(val);
    if (ax == 0.0) return sign;
    if (std.math.isInf(ax) or ax >= 448.0) return sign | 0x7E;
    if (ax < 0.015625) {
        const scaled: f32 = ax * 512.0;
        const floored: f32 = @floor(scaled);
        var man: u32 = @intFromFloat(floored);
        const frac: f32 = scaled - floored;
        if (frac > 0.5 or (frac == 0.5 and (man & 1) != 0)) man += 1;
        if (man >= 8) return sign | 0x08;
        return sign | @as(u8, @intCast(man));
    }
    const u: u32 = @bitCast(ax);
    const f_exp: i32 = @as(i32, @intCast((u >> 23) & 0xFF)) - 127;
    var exp4: i32 = f_exp + 7;
    var man: u32 = (u >> 20) & 0x07;
    const rem: u32 = u & 0x000F_FFFF;
    if (rem > 0x0008_0000 or (rem == 0x0008_0000 and (man & 1) != 0)) {
        man += 1;
        if (man == 8) {
            man = 0;
            exp4 += 1;
        }
    }
    if (exp4 > 15 or (exp4 == 15 and man >= 7)) return sign | 0x7E;
    return sign | @as(u8, @intCast((@as(u32, @intCast(exp4)) << 3) | man));
}

/// Decodes NVFP4 micro-scale byte (`E4M3`, treating `0x7F`/`0xFF` as `0.0` per `ggml_ue4m3_to_fp32`).
pub inline fn nvfp4ScaleToF32(bits: u8) f32 {
    if ((bits & 0x7F) == 0x7F) return 0.0;
    return e4m3ToF32(bits);
}

/// Decodes OCP `UE8M0` exponent byte (`e == 255 -> NaN`, `e == 0 -> 2^-127`, `else -> 2^(e-127)`).
pub fn ue8m0ToF32(e: u8) f32 {
    if (e == 255) return std.math.nan(f32);
    if (e == 0) return @bitCast(@as(u32, 0x0040_0000));
    return @bitCast(@as(u32, e) << 23);
}

pub const E2M1_TABLE: [16]f32 = .{
    0.0,  0.5,  1.0,  1.5,  2.0,  3.0,  4.0,  6.0,
    -0.0, -0.5, -1.0, -1.5, -2.0, -3.0, -4.0, -6.0,
};

pub inline fn e2m1ToF32(nibble: u4) f32 {
    return E2M1_TABLE[nibble];
}

/// Quantizes `val` to nearest `E2M1` code with IEEE ties-to-even rounding.
pub fn f32ToE2m1(val: f32) u4 {
    const sign: u4 = if (std.math.signbit(val)) 0x8 else 0x0;
    if (std.math.isNan(val)) return sign | 0x7;
    const ax: f32 = @abs(val);
    const code: u4 = if (ax <= 0.25)
        0
    else if (ax < 0.75)
        1
    else if (ax <= 1.25)
        2
    else if (ax < 1.75)
        3
    else if (ax <= 2.5)
        4
    else if (ax < 3.5)
        5
    else if (ax <= 5.0)
        6
    else
        7;
    return sign | code;
}

