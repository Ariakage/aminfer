            const sb: spec.ScaleBias = .{ .scale = @floatCast(0.125), .bias = @floatCast(-0.5) };
            var deq: [gs]f32 = undefined;
            Ops.dequantizeGroup(&packed_buf, sb, &deq);
            for (deq, 0..) |val, idx| {
                const expected: f32 = @as(f32, @floatFromInt(codes[idx])) * 0.125 - 0.5;
