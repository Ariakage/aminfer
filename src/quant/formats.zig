            const mask: usize = (@as(usize, 1) << @intCast(bw)) - 1;
            for (&codes, 0..) |*c, idx| c.* = @intCast((idx * 7 + 3) & mask);

            var packed_buf: [Ops.groupWeightBytes()]u8 = undefined;
