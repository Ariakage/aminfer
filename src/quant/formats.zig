/// Compile-time specialized MLX-compatible affine group quantization for
/// `bits in {2, 3, 4, 5, 6, 8}` and `group_size in {32, 64, 128}`.
pub fn AffineQuantOps(comptime qspec: AffineSpec) type {
    if (qspec.group_size != 32 and qspec.group_size != 64 and qspec.group_size != 128) {
        @compileError("AffineQuantOps requires group_size in {32, 64, 128}");
    }
    const bits: usize = qspec.bits.bitWidth();
    const gs: usize = qspec.group_size;
    const group_bytes: usize = (gs * bits) / 8;

    return struct {
        pub const quant_spec: AffineSpec = qspec;

        pub inline fn groupWeightBytes() usize {
            return group_bytes;
        }

        pub inline fn groupsPerRow(k: usize) spec.ShapeError!usize {
            if (k == 0) return error.ZeroDimension;
            if (k % gs != 0) return error.UnalignedK;
            return k / gs;
        }

        pub inline fn rowWeightBytes(k: usize) spec.ShapeError!usize {
            const groups = try groupsPerRow(k);
            return std.math.mul(usize, groups, group_bytes) catch return error.Overflow;
        }

        pub inline fn packedWeightBytes(n: usize, k: usize) spec.ShapeError!usize {
            if (n == 0) return error.ZeroDimension;
            const rb = try rowWeightBytes(k);
            return std.math.mul(usize, n, rb) catch return error.Overflow;
        }

        pub inline fn scaleBiasBytes(n: usize, k: usize) spec.ShapeError!usize {
            if (n == 0) return error.ZeroDimension;
            const groups = try groupsPerRow(k);
            const total_groups = std.math.mul(usize, n, groups) catch return error.Overflow;
            return std.math.mul(usize, total_groups, @sizeOf(spec.ScaleBias)) catch return error.Overflow;
        }

        /// Packs `group_size` unsigned integer codes into MLX LSB-first bitstream.
        pub fn packGroup(codes: *const [gs]u8, out: *[group_bytes]u8) void {
            switch (qspec.bits) {
                .q2 => {
                    for (0..gs / 4) |i| {
                        out[i] = (codes[4 * i] & 0x03) |
                            ((codes[4 * i + 1] & 0x03) << 2) |
                            ((codes[4 * i + 2] & 0x03) << 4) |
                            ((codes[4 * i + 3] & 0x03) << 6);
                    }
                },
                .q3 => {
                    for (0..gs / 8) |blk| {
                        const c = codes[blk * 8 ..][0..8];
                        var word: u24 = 0;
                        inline for (0..8) |j| {
                            word |= @as(u24, c[j] & 0x07) << @intCast(j * 3);
                        }
                        out[blk * 3 + 0] = @truncate(word);
                        out[blk * 3 + 1] = @truncate(word >> 8);
                        out[blk * 3 + 2] = @truncate(word >> 16);
                    }
                },
                .q4 => {
                    for (0..gs / 2) |i| {
                        out[i] = (codes[2 * i] & 0x0F) | ((codes[2 * i + 1] & 0x0F) << 4);
                    }
                },
                .q5 => {
                    for (0..gs / 8) |blk| {
                        const c = codes[blk * 8 ..][0..8];
                        var word: u40 = 0;
                        inline for (0..8) |j| {
                            word |= @as(u40, c[j] & 0x1F) << @intCast(j * 5);
                        }
                        inline for (0..5) |b| {
                            out[blk * 5 + b] = @truncate(word >> @intCast(b * 8));
                        }
                    }
                },
                .q6 => {
                    for (0..gs / 4) |blk| {
                        const c = codes[blk * 4 ..][0..4];
                        var word: u24 = 0;
                        inline for (0..4) |j| {
                            word |= @as(u24, c[j] & 0x3F) << @intCast(j * 6);
                        }
                        out[blk * 3 + 0] = @truncate(word);
                        out[blk * 3 + 1] = @truncate(word >> 8);
                        out[blk * 3 + 2] = @truncate(word >> 16);
                    }
                },
                .q8 => @memcpy(out, codes),
            }
        }

        /// Dequantizes one MLX affine group to `f32` (`q * scale + bias`).
        pub fn dequantizeGroup(packed_group: *const [group_bytes]u8, sb: spec.ScaleBias, out: *[gs]f32) void {
            const scale: f32 = @floatCast(sb.scale);
            const bias: f32 = @floatCast(sb.bias);
            switch (qspec.bits) {
                .q2 => {
                    for (0..gs / 4) |i| {
                        const byte = packed_group[i];
                        inline for (0..4) |j| {
                            const q: u8 = (byte >> @intCast(j * 2)) & 0x03;
                            out[4 * i + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                        }
                    }
                },
                .q3 => {
                    for (0..gs / 8) |blk| {
                        const word: u24 = @as(u24, packed_group[blk * 3 + 0]) |
                            (@as(u24, packed_group[blk * 3 + 1]) << 8) |
                            (@as(u24, packed_group[blk * 3 + 2]) << 16);
                        inline for (0..8) |j| {
                            const q: u8 = @intCast((word >> @intCast(j * 3)) & 0x07);
                            out[blk * 8 + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                        }
                    }
                },
                .q4 => {
                    for (0..gs / 2) |i| {
                        const byte = packed_group[i];
                        out[2 * i] = @as(f32, @floatFromInt(byte & 0x0F)) * scale + bias;
                        out[2 * i + 1] = @as(f32, @floatFromInt(byte >> 4)) * scale + bias;
                    }
                },
                .q5 => {
                    for (0..gs / 8) |blk| {
                        var word: u40 = 0;
                        inline for (0..5) |b| {
                            word |= @as(u40, packed_group[blk * 5 + b]) << @intCast(b * 8);
                        }
                        inline for (0..8) |j| {
                            const q: u8 = @intCast((word >> @intCast(j * 5)) & 0x1F);
                            out[blk * 8 + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                        }
                    }
                },
                .q6 => {
                    for (0..gs / 4) |blk| {
                        const word: u24 = @as(u24, packed_group[blk * 3 + 0]) |
                            (@as(u24, packed_group[blk * 3 + 1]) << 8) |
                            (@as(u24, packed_group[blk * 3 + 2]) << 16);
                        inline for (0..4) |j| {
                            const q: u8 = @intCast((word >> @intCast(j * 6)) & 0x3F);
                            out[blk * 4 + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                        }
                    }
                },
                .q8 => {
                    for (0..gs) |i| {
                        out[i] = @as(f32, @floatFromInt(packed_group[i])) * scale + bias;
                    }
                },
            }
        }
    };
}

