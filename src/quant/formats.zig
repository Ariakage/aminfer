fn dequantAffineRow(
    comptime bits: AffineQuantBits,
    row_data: []const u8,
    row_params: []const u8,
    k: usize,
    group_size: u16,
    out_row: []f32,
) Error!void {
    switch (group_size) {
        32 => try dequantAffineRowFixed(bits, 32, row_data, row_params, k, out_row),
        64 => try dequantAffineRowFixed(bits, 64, row_data, row_params, k, out_row),
        128 => try dequantAffineRowFixed(bits, 128, row_data, row_params, k, out_row),
        else => return error.InvalidGroupSize,
    }
}

fn dequantAffineRowFixed(
    comptime bits: AffineQuantBits,
    comptime gs: u16,
    row_data: []const u8,
    row_params: []const u8,
    k: usize,
    out_row: []f32,
) Error!void {
    const Ops = AffineQuantOps(.{ .bits = bits, .group_size = gs });
    const groups = try Ops.groupsPerRow(k);
    const grp_bytes = Ops.groupWeightBytes();
    if (row_data.len < groups * grp_bytes or row_params.len < groups * 4) return error.BufferTooSmall;
    var tmp: [gs]f32 = undefined;
    for (0..groups) |g| {
        const sb: spec.ScaleBias = .{
            .scale = @bitCast(readU16(row_params, g * 4 + 0)),
            .bias = @bitCast(readU16(row_params, g * 4 + 2)),
        };
        Ops.dequantizeGroup(row_data[g * grp_bytes ..][0..grp_bytes], sb, &tmp);
        @memcpy(out_row[g * gs ..][0..gs], &tmp);
    }
}

fn dequantGgufRow(
    dtype: DType,
    row_bytes: []const u8,
    k: usize,
    out_row: []f32,
) Error!void {
    const info = ggufBlockInfo(dtype) orelse return error.UnsupportedDType;
    const qk: usize = info.block_elems;
    const bs: usize = info.block_bytes;
    if (k % qk != 0) return error.UnalignedK;
    const nb = k / qk;
    if (row_bytes.len < nb * bs) return error.BufferTooSmall;

    for (0..nb) |b| {
        const blk = row_bytes[b * bs ..][0..bs];
        const y = out_row[b * qk ..][0..qk];
        switch (dtype) {
            .gguf_q4_0 => {
                const d = readF16(blk, 0);
                for (0..16) |j| {
                    const byte = blk[2 + j];
                    y[j] = @as(f32, @floatFromInt(@as(i32, byte & 0x0F) - 8)) * d;
                    y[j + 16] = @as(f32, @floatFromInt(@as(i32, byte >> 4) - 8)) * d;
                }
            },
            .gguf_q4_1 => {
                const d = readF16(blk, 0);
                const m = readF16(blk, 2);
                for (0..16) |j| {
                    const byte = blk[4 + j];
                    y[j] = @as(f32, @floatFromInt(byte & 0x0F)) * d + m;
                    y[j + 16] = @as(f32, @floatFromInt(byte >> 4)) * d + m;
                }
            },
            .gguf_q5_0 => {
                const d = readF16(blk, 0);
                const qh = readU32(blk, 2);
                for (0..16) |j| {
                    const byte = blk[6 + j];
                    const xh_0: i32 = @intCast(((qh >> @intCast(j)) << 4) & 0x10);
                    const xh_1: i32 = @intCast((qh >> @intCast(j + 12)) & 0x10);
                    const x0: i32 = (@as(i32, byte & 0x0F) | xh_0) - 16;
                    const x1: i32 = (@as(i32, byte >> 4) | xh_1) - 16;
                    y[j] = @as(f32, @floatFromInt(x0)) * d;
                    y[j + 16] = @as(f32, @floatFromInt(x1)) * d;
                }
            },
            .gguf_q5_1 => {
                const d = readF16(blk, 0);
                const m = readF16(blk, 2);
                const qh = readU32(blk, 4);
                for (0..16) |j| {
                    const byte = blk[8 + j];
                    const xh_0: u8 = @intCast(((qh >> @intCast(j)) << 4) & 0x10);
                    const xh_1: u8 = @intCast((qh >> @intCast(j + 12)) & 0x10);
                    y[j] = @as(f32, @floatFromInt((byte & 0x0F) | xh_0)) * d + m;
                    y[j + 16] = @as(f32, @floatFromInt((byte >> 4) | xh_1)) * d + m;
                }
            },
            .gguf_q8_0 => {
                const d = readF16(blk, 0);
                for (0..32) |j| {
                    const q: i8 = @bitCast(blk[2 + j]);
                    y[j] = @as(f32, @floatFromInt(q)) * d;
                }
            },
            .gguf_q2_0 => {
                const d = readF16(blk, 0);
                for (0..64) |j| {
                    const byte_idx = j / 4;
                    const bit_off: u3 = @intCast((j % 4) * 2);
                    const q: i32 = @intCast((blk[2 + byte_idx] >> bit_off) & 0x03);
                    y[j] = @as(f32, @floatFromInt(q - 1)) * d;
                }
            },
            .gguf_mxfp4 => {
                const d = ue8m0ToF32(blk[0]) * 0.5;
                for (0..16) |j| {
                    const byte = blk[1 + j];
                    const x0 = kvalues_mxfp4[byte & 0x0F];
                    const x1 = kvalues_mxfp4[byte >> 4];
                    y[j] = @as(f32, @floatFromInt(x0)) * d;
                    y[j + 16] = @as(f32, @floatFromInt(x1)) * d;
                }
            },
            .gguf_q2_k => {
                const scales = blk[0..16];
                const d = readF16(blk, 80);
                const min = readF16(blk, 82);
                var q_off: usize = 16;
                var y_off: usize = 0;
                var is: usize = 0;
                for (0..2) |_| {
                    var shift: u3 = 0;
                    for (0..4) |_| {
                        const sc0 = scales[is];
                        is += 1;
                        const dl0 = d * @as(f32, @floatFromInt(sc0 & 0x0F));
                        const ml0 = min * @as(f32, @floatFromInt(sc0 >> 4));
                        for (0..16) |l| {
                            y[y_off + l] = dl0 * @as(f32, @floatFromInt((blk[q_off + l] >> shift) & 3)) - ml0;
                        }
                        y_off += 16;

                        const sc1 = scales[is];
                        is += 1;
                        const dl1 = d * @as(f32, @floatFromInt(sc1 & 0x0F));
                        const ml1 = min * @as(f32, @floatFromInt(sc1 >> 4));
                        for (0..16) |l| {
                            y[y_off + l] = dl1 * @as(f32, @floatFromInt((blk[q_off + 16 + l] >> shift) & 3)) - ml1;
                        }
                        y_off += 16;
                        shift +%= 2;
                    }
                    q_off += 32;
                }
            },
            .gguf_q3_k => {
                const hm = blk[0..32];
                const qs = blk[32..96];
                const d_all = readF16(blk, 108);
                var aux: [4]u32 = .{
                    readU32(blk, 96),
                    readU32(blk, 100),
                    readU32(blk, 104),
                    0,
                };
                const kmask1: u32 = 0x03030303;
                const kmask2: u32 = 0x0f0f0f0f;
                const tmp = aux[2];
                aux[2] = ((aux[0] >> 4) & kmask2) | (((tmp >> 4) & kmask1) << 4);
                aux[3] = ((aux[1] >> 4) & kmask2) | (((tmp >> 6) & kmask1) << 4);
                aux[0] = (aux[0] & kmask2) | (((tmp >> 0) & kmask1) << 4);
                aux[1] = (aux[1] & kmask2) | (((tmp >> 2) & kmask1) << 4);
                const sc_bytes: []const i8 = std.mem.bytesAsSlice(i8, std.mem.asBytes(&aux));

                var q_off: usize = 0;
                var y_off: usize = 0;
                var is: usize = 0;
                var m: u8 = 1;
                for (0..2) |_| {
                    var shift: u3 = 0;
                    for (0..4) |_| {
                        const dl0 = d_all * @as(f32, @floatFromInt(@as(i32, sc_bytes[is]) - 32));
                        is += 1;
                        for (0..16) |l| {
                            const q2: i32 = @intCast((qs[q_off + l] >> shift) & 3);
                            const h_sub: i32 = if ((hm[l] & m) != 0) 0 else 4;
                            y[y_off + l] = dl0 * @as(f32, @floatFromInt(q2 - h_sub));
                        }
                        y_off += 16;

                        const dl1 = d_all * @as(f32, @floatFromInt(@as(i32, sc_bytes[is]) - 32));
                        is += 1;
                        for (0..16) |l| {
                            const q2: i32 = @intCast((qs[q_off + 16 + l] >> shift) & 3);
                            const h_sub: i32 = if ((hm[16 + l] & m) != 0) 0 else 4;
                            y[y_off + l] = dl1 * @as(f32, @floatFromInt(q2 - h_sub));
                        }
                        y_off += 16;
                        shift +%= 2;
                        m <<= 1;
                    }
                    q_off += 32;
                }
            },
            .gguf_q4_k => {
                const d = readF16(blk, 0);
                const min = readF16(blk, 2);
                const scales = blk[4..16];
                const qs = blk[16..144];
                var q_off: usize = 0;
                var y_off: usize = 0;
                var is: usize = 0;
                for (0..4) |_| {
                    const sm0 = getScaleMinK4(is + 0, scales);
                    const sm1 = getScaleMinK4(is + 1, scales);
                    const d1 = d * @as(f32, @floatFromInt(sm0.sc));
                    const m1 = min * @as(f32, @floatFromInt(sm0.m));
                    const d2 = d * @as(f32, @floatFromInt(sm1.sc));
                    const m2 = min * @as(f32, @floatFromInt(sm1.m));
                    for (0..32) |l| y[y_off + l] = d1 * @as(f32, @floatFromInt(qs[q_off + l] & 0x0F)) - m1;
                    for (0..32) |l| y[y_off + 32 + l] = d2 * @as(f32, @floatFromInt(qs[q_off + l] >> 4)) - m2;
                    q_off += 32;
                    y_off += 64;
                    is += 2;
                }
            },
            .gguf_q5_k => {
                const d = readF16(blk, 0);
                const min = readF16(blk, 2);
                const scales = blk[4..16];
                const qh = blk[16..48];
                const ql = blk[48..176];
                var q_off: usize = 0;
                var y_off: usize = 0;
                var is: usize = 0;
                var mask1: u8 = 1;
                var mask2: u8 = 2;
                for (0..4) |_| {
                    const sm0 = getScaleMinK4(is + 0, scales);
                    const sm1 = getScaleMinK4(is + 1, scales);
                    const d1 = d * @as(f32, @floatFromInt(sm0.sc));
                    const m1 = min * @as(f32, @floatFromInt(sm0.m));
                    const d2 = d * @as(f32, @floatFromInt(sm1.sc));
                    const m2 = min * @as(f32, @floatFromInt(sm1.m));
                    for (0..32) |l| {
                        const h: u8 = if ((qh[l] & mask1) != 0) 16 else 0;
                        y[y_off + l] = d1 * @as(f32, @floatFromInt((ql[q_off + l] & 0x0F) + h)) - m1;
                    }
                    for (0..32) |l| {
                        const h: u8 = if ((qh[l] & mask2) != 0) 16 else 0;
                        y[y_off + 32 + l] = d2 * @as(f32, @floatFromInt((ql[q_off + l] >> 4) + h)) - m2;
                    }
                    q_off += 32;
                    y_off += 64;
                    is += 2;
                    mask1 <<= 2;
                    mask2 <<= 2;
                }
            },
            .gguf_q6_k => {
                const d = readF16(blk, 208);
                var ql_off: usize = 0;
                var qh_off: usize = 128;
                var sc_off: usize = 192;
                var y_off: usize = 0;
                for (0..2) |_| {
                    for (0..32) |l| {
                        const is: usize = l / 16;
                        const qh_b = blk[qh_off + l];
                        const q1: i32 = @as(i32, @intCast((blk[ql_off + l] & 0x0F) | (((qh_b >> 0) & 3) << 4))) - 32;
                        const q2: i32 = @as(i32, @intCast((blk[ql_off + l + 32] & 0x0F) | (((qh_b >> 2) & 3) << 4))) - 32;
                        const q3: i32 = @as(i32, @intCast((blk[ql_off + l] >> 4) | (((qh_b >> 4) & 3) << 4))) - 32;
                        const q4: i32 = @as(i32, @intCast((blk[ql_off + l + 32] >> 4) | (((qh_b >> 6) & 3) << 4))) - 32;
                        const s0: i8 = @bitCast(blk[sc_off + is + 0]);
                        const s2: i8 = @bitCast(blk[sc_off + is + 2]);
                        const s4: i8 = @bitCast(blk[sc_off + is + 4]);
                        const s6: i8 = @bitCast(blk[sc_off + is + 6]);
                        y[y_off + l + 0] = d * @as(f32, @floatFromInt(s0)) * @as(f32, @floatFromInt(q1));
                        y[y_off + l + 32] = d * @as(f32, @floatFromInt(s2)) * @as(f32, @floatFromInt(q2));
                        y[y_off + l + 64] = d * @as(f32, @floatFromInt(s4)) * @as(f32, @floatFromInt(q3));
                        y[y_off + l + 96] = d * @as(f32, @floatFromInt(s6)) * @as(f32, @floatFromInt(q4));
                    }
                    y_off += 128;
                    ql_off += 64;
                    qh_off += 32;
                    sc_off += 8;
                }
            },
            .gguf_iq1_s => {
                const d = readF16(blk, 0);
                const qs = blk[2..34];
                var q_off: usize = 0;
                var y_off: usize = 0;
                for (0..8) |ib| {
                    const qh_word = readU16(blk, 34 + ib * 2);
                    const dl = d * @as(f32, @floatFromInt(2 * ((qh_word >> 12) & 7) + 1));
                    const delta: f32 = if ((qh_word & 0x8000) != 0) -0.125 else 0.125;
                    for (0..4) |l| {
                        const grid_idx = @as(usize, qs[q_off + l]) | (@as(usize, (qh_word >> @intCast(3 * l)) & 7) << 8);
                        const grid = iq1s_grid[grid_idx];
                        for (0..8) |j| {
                            const g_signed: i8 = @bitCast(@as(u8, @truncate(grid >> @intCast(j * 8))));
                            y[y_off + j] = dl * (@as(f32, @floatFromInt(g_signed)) + delta);
                        }
                        y_off += 8;
                    }
                    q_off += 4;
                }
            },
            .gguf_iq1_m => {
                const sc_bytes = blk[48..56];
                const sc0 = readU16(sc_bytes, 0);
                const sc1 = readU16(sc_bytes, 2);
                const sc2 = readU16(sc_bytes, 4);
                const sc3 = readU16(sc_bytes, 6);
                const d_bits: u16 = (sc0 >> 12) | ((sc1 >> 8) & 0x00f0) | ((sc2 >> 4) & 0x0f00) | (sc3 & 0xf000);
                const d: f32 = @floatCast(@as(f16, @bitCast(d_bits)));
                const qs = blk[0..32];
                const qh = blk[32..48];
                var q_off: usize = 0;
                var qh_off: usize = 0;
                var y_off: usize = 0;
                for (0..8) |ib| {
                    const sc_w = readU16(sc_bytes, (ib / 2) * 2);
                    const shift_base: u4 = @intCast(6 * (ib % 2));
                    const dl1 = d * @as(f32, @floatFromInt(2 * ((sc_w >> shift_base) & 0x7) + 1));
                    const dl2 = d * @as(f32, @floatFromInt(2 * ((sc_w >> (shift_base + 3)) & 0x7) + 1));
                    const idx = [4]usize{
                        @as(usize, qs[q_off + 0]) | ((@as(usize, qh[qh_off + 0]) << 8) & 0x700),
                        @as(usize, qs[q_off + 1]) | ((@as(usize, qh[qh_off + 0]) << 4) & 0x700),
                        @as(usize, qs[q_off + 2]) | ((@as(usize, qh[qh_off + 1]) << 8) & 0x700),
                        @as(usize, qs[q_off + 3]) | ((@as(usize, qh[qh_off + 1]) << 4) & 0x700),
                    };
                    const delta = [4]f32{
                        if ((qh[qh_off + 0] & 0x08) != 0) -0.125 else 0.125,
                        if ((qh[qh_off + 0] & 0x80) != 0) -0.125 else 0.125,
                        if ((qh[qh_off + 1] & 0x08) != 0) -0.125 else 0.125,
                        if ((qh[qh_off + 1] & 0x80) != 0) -0.125 else 0.125,
                    };
                    for (0..2) |l| {
                        const grid = iq1s_grid[idx[l]];
                        for (0..8) |j| {
                            const g_signed: i8 = @bitCast(@as(u8, @truncate(grid >> @intCast(j * 8))));
                            y[y_off + j] = dl1 * (@as(f32, @floatFromInt(g_signed)) + delta[l]);
                        }
                        y_off += 8;
                    }
                    for (2..4) |l| {
                        const grid = iq1s_grid[idx[l]];
                        for (0..8) |j| {
                            const g_signed: i8 = @bitCast(@as(u8, @truncate(grid >> @intCast(j * 8))));
                            y[y_off + j] = dl2 * (@as(f32, @floatFromInt(g_signed)) + delta[l]);
                        }
                        y_off += 8;
                    }
                    q_off += 4;
                    qh_off += 2;
                }
            },
            .gguf_iq2_xxs => {
                const d = readF16(blk, 0);
                var y_off: usize = 0;
                for (0..8) |ib32| {
                    const aux0 = readU32(blk, 2 + ib32 * 8);
                    const aux1 = readU32(blk, 2 + ib32 * 8 + 4);
                    const db = d * (0.5 + @as(f32, @floatFromInt(aux1 >> 28))) * 0.25;
                    for (0..4) |l| {
                        const g_idx: u8 = @truncate(aux0 >> @intCast(l * 8));
                        const grid = iq2xxs_grid[g_idx];
                        const signs = ksigns_iq2xs[(aux1 >> @intCast(7 * l)) & 127];
                        for (0..8) |j| {
                            const g_byte: u8 = @truncate(grid >> @intCast(j * 8));
                            const sgn: f32 = if ((signs & kmask_iq2xs[j]) != 0) -1.0 else 1.0;
                            y[y_off + j] = db * @as(f32, @floatFromInt(g_byte)) * sgn;
                        }
                        y_off += 8;
                    }
                }
            },
            .gguf_iq2_xs => {
                const d = readF16(blk, 0);
                const scales = blk[66..74];
                var y_off: usize = 0;
                for (0..8) |ib32| {
                    const db = [2]f32{
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] & 0x0F))) * 0.25,
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] >> 4))) * 0.25,
                    };
                    for (0..4) |l| {
                        const qs_w = readU16(blk, 2 + (4 * ib32 + l) * 2);
                        const grid = iq2xs_grid[qs_w & 511];
                        const signs = ksigns_iq2xs[qs_w >> 9];
                        const dl = db[l / 2];
                        for (0..8) |j| {
                            const g_byte: u8 = @truncate(grid >> @intCast(j * 8));
                            const sgn: f32 = if ((signs & kmask_iq2xs[j]) != 0) -1.0 else 1.0;
                            y[y_off + j] = dl * @as(f32, @floatFromInt(g_byte)) * sgn;
                        }
                        y_off += 8;
                    }
                }
            },
            .gguf_iq2_s => {
                const d = readF16(blk, 0);
                const qs_all = blk[2..66];
                const qh = blk[66..74];
                const scales = blk[74..82];
                var qs_off: usize = 0;
                var signs_off: usize = 32;
                var y_off: usize = 0;
                for (0..8) |ib32| {
                    const db = [2]f32{
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] & 0x0F))) * 0.25,
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] >> 4))) * 0.25,
                    };
                    for (0..4) |l| {
                        const dl = db[l / 2];
                        const qh_hi: usize = (@as(usize, qh[ib32]) << @intCast(8 - 2 * l)) & 0x300;
                        const grid = iq2s_grid[@as(usize, qs_all[qs_off + l]) | qh_hi];
                        const sign_b = qs_all[signs_off + l];
                        for (0..8) |j| {
                            const g_byte: u8 = @truncate(grid >> @intCast(j * 8));
                            const sgn: f32 = if ((sign_b & kmask_iq2xs[j]) != 0) -1.0 else 1.0;
                            y[y_off + j] = dl * @as(f32, @floatFromInt(g_byte)) * sgn;
                        }
                        y_off += 8;
                    }
                    qs_off += 4;
                    signs_off += 4;
                }
            },
            .gguf_iq3_xxs => {
                const d = readF16(blk, 0);
                const qs = blk[2..66];
                const sc_signs = blk[66..98];
                var qs_off: usize = 0;
                var y_off: usize = 0;
                for (0..8) |ib32| {
                    const aux32 = readU32(sc_signs, 4 * ib32);
                    const db = d * (0.5 + @as(f32, @floatFromInt(aux32 >> 28))) * 0.5;
                    for (0..4) |l| {
                        const signs = ksigns_iq2xs[(aux32 >> @intCast(7 * l)) & 127];
                        const g1 = iq3xxs_grid[qs[qs_off + 2 * l + 0]];
                        const g2 = iq3xxs_grid[qs[qs_off + 2 * l + 1]];
                        for (0..4) |j| {
                            const b1: u8 = @truncate(g1 >> @intCast(j * 8));
                            const b2: u8 = @truncate(g2 >> @intCast(j * 8));
                            const s1: f32 = if ((signs & kmask_iq2xs[j + 0]) != 0) -1.0 else 1.0;
                            const s2: f32 = if ((signs & kmask_iq2xs[j + 4]) != 0) -1.0 else 1.0;
                            y[y_off + j + 0] = db * @as(f32, @floatFromInt(b1)) * s1;
                            y[y_off + j + 4] = db * @as(f32, @floatFromInt(b2)) * s2;
                        }
                        y_off += 8;
                    }
                    qs_off += 8;
                }
            },
            .gguf_iq3_s => {
                const d = readF16(blk, 0);
                const qs = blk[2..66];
                const qh = blk[66..74];
                const signs_all = blk[74..106];
                const scales = blk[106..110];
                var qs_off: usize = 0;
                var qh_off: usize = 0;
                var signs_off: usize = 0;
                var y_off: usize = 0;
                for (0..4) |pair| {
                    const sc_b = scales[pair];
                    const db1 = d * @as(f32, @floatFromInt(1 + 2 * (sc_b & 0x0F)));
                    const db2 = d * @as(f32, @floatFromInt(1 + 2 * (sc_b >> 4)));
                    for (0..4) |l| {
                        const idx1 = @as(usize, qs[qs_off + 2 * l + 0]) | ((@as(usize, qh[qh_off + 0]) << @intCast(8 - 2 * l)) & 256);
                        const idx2 = @as(usize, qs[qs_off + 2 * l + 1]) | ((@as(usize, qh[qh_off + 0]) << @intCast(7 - 2 * l)) & 256);
                        const g1 = iq3s_grid[idx1];
                        const g2 = iq3s_grid[idx2];
                        const sb = signs_all[signs_off + l];
                        for (0..4) |j| {
                            const b1: u8 = @truncate(g1 >> @intCast(j * 8));
                            const b2: u8 = @truncate(g2 >> @intCast(j * 8));
                            const s1: f32 = if ((sb & kmask_iq2xs[j + 0]) != 0) -1.0 else 1.0;
                            const s2: f32 = if ((sb & kmask_iq2xs[j + 4]) != 0) -1.0 else 1.0;
                            y[y_off + j + 0] = db1 * @as(f32, @floatFromInt(b1)) * s1;
                            y[y_off + j + 4] = db1 * @as(f32, @floatFromInt(b2)) * s2;
                        }
                        y_off += 8;
                    }
                    qs_off += 8;
                    signs_off += 4;
                    for (0..4) |l| {
                        const idx1 = @as(usize, qs[qs_off + 2 * l + 0]) | ((@as(usize, qh[qh_off + 1]) << @intCast(8 - 2 * l)) & 256);
                        const idx2 = @as(usize, qs[qs_off + 2 * l + 1]) | ((@as(usize, qh[qh_off + 1]) << @intCast(7 - 2 * l)) & 256);
                        const g1 = iq3s_grid[idx1];
                        const g2 = iq3s_grid[idx2];
                        const sb = signs_all[signs_off + l];
                        for (0..4) |j| {
                            const b1: u8 = @truncate(g1 >> @intCast(j * 8));
                            const b2: u8 = @truncate(g2 >> @intCast(j * 8));
                            const s1: f32 = if ((sb & kmask_iq2xs[j + 0]) != 0) -1.0 else 1.0;
                            const s2: f32 = if ((sb & kmask_iq2xs[j + 4]) != 0) -1.0 else 1.0;
                            y[y_off + j + 0] = db2 * @as(f32, @floatFromInt(b1)) * s1;
                            y[y_off + j + 4] = db2 * @as(f32, @floatFromInt(b2)) * s2;
                        }
                        y_off += 8;
                    }
                    qh_off += 2;
                    qs_off += 8;
                    signs_off += 4;
                }
            },
            .gguf_iq4_nl => {
                const d = readF16(blk, 0);
                for (0..16) |j| {
                    const byte = blk[2 + j];
                    y[j + 0] = d * @as(f32, @floatFromInt(kvalues_iq4nl[byte & 0x0F]));
                    y[j + 16] = d * @as(f32, @floatFromInt(kvalues_iq4nl[byte >> 4]));
                }
            },
            .gguf_iq4_xs => {
                const d = readF16(blk, 0);
                const scales_h = readU16(blk, 2);
                const scales_l = blk[4..8];
                const qs = blk[8..136];
                for (0..8) |ib| {
                    const ls_lo: i32 = @intCast((scales_l[ib / 2] >> @intCast(4 * (ib % 2))) & 0x0F);
                    const ls_hi: i32 = @intCast(((scales_h >> @intCast(2 * ib)) & 3) << 4);
                    const dl = d * @as(f32, @floatFromInt((ls_lo | ls_hi) - 32));
                    const q_sub = qs[ib * 16 ..][0..16];
                    const y_sub = y[ib * 32 ..][0..32];
                    for (0..16) |j| {
                        y_sub[j + 0] = dl * @as(f32, @floatFromInt(kvalues_iq4nl[q_sub[j] & 0x0F]));
                        y_sub[j + 16] = dl * @as(f32, @floatFromInt(kvalues_iq4nl[q_sub[j] >> 4]));
                    }
                }
            },
            .gguf_tq1_0 => {
                const pow3 = [5]u8{ 1, 3, 9, 27, 81 };
                const qs = blk[0..48];
                const qh = blk[48..52];
                const d = readF16(blk, 52);
                var y_off: usize = 0;
                for (0..5) |n| {
                    for (0..32) |m| {
                        const q: u8 = qs[m] *% pow3[n];
                        const xi: i32 = @intCast((@as(u16, q) * 3) >> 8);
                        y[y_off] = @as(f32, @floatFromInt(xi - 1)) * d;
                        y_off += 1;
                    }
                }
                for (0..5) |n| {
                    for (0..16) |m| {
                        const q: u8 = qs[32 + m] *% pow3[n];
                        const xi: i32 = @intCast((@as(u16, q) * 3) >> 8);
                        y[y_off] = @as(f32, @floatFromInt(xi - 1)) * d;
                        y_off += 1;
                    }
                }
                for (0..4) |n| {
                    for (0..4) |j| {
                        const q: u8 = qh[j] *% pow3[n];
                        const xi: i32 = @intCast((@as(u16, q) * 3) >> 8);
                        y[y_off] = @as(f32, @floatFromInt(xi - 1)) * d;
                        y_off += 1;
                    }
                }
            },
            .gguf_tq2_0 => {
                const qs = blk[0..64];
                const d = readF16(blk, 64);
                var y_off: usize = 0;
                var j: usize = 0;
                while (j < 64) : (j += 32) {
                    for (0..4) |l| {
                        for (0..32) |m| {
                            const q: i32 = @intCast((qs[j + m] >> @intCast(l * 2)) & 3);
                            y[y_off] = @as(f32, @floatFromInt(q - 1)) * d;
                            y_off += 1;
                        }
                    }
                }
            },
            else => return error.UnsupportedDType,
        }
    }
}

/// Dequantizes row `row_idx` of a `[n, k]` weight matrix of any supported `.amf`
/// `DType` (`0..37`, except integer `.u32`) into `out_row[0..k]` (`f32`).
pub fn dequantRowCpuRef(
    dtype: DType,
    data: []const u8,
    params: []const u8,
    n: usize,
    k: usize,
    row_idx: usize,
    group_size: u16,
    out_row: []f32,
) Error!void {
    if (n == 0 or k == 0) return error.ZeroDimension;
    if (row_idx >= n) return error.OutOfBounds;
    if (out_row.len < k) return error.BufferTooSmall;

    switch (dtype) {
        .u32 => return error.UnsupportedDType,
        .f16 => {
            const rb = std.math.mul(usize, k, 2) catch return error.Overflow;
            const total = std.math.mul(usize, n, rb) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            const base = row_idx * rb;
            for (0..k) |col| out_row[col] = readF16(data, base + col * 2);
        },
        .bf16 => {
            const rb = std.math.mul(usize, k, 2) catch return error.Overflow;
            const total = std.math.mul(usize, n, rb) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            const base = row_idx * rb;
            for (0..k) |col| out_row[col] = spec.bf16ToF32(readU16(data, base + col * 2));
        },
        .f32 => {
            const rb = std.math.mul(usize, k, 4) catch return error.Overflow;
            const total = std.math.mul(usize, n, rb) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            const base = row_idx * rb;
            for (0..k) |col| out_row[col] = readF32(data, base + col * 4);
        },
        .q2_affine, .q3_affine, .q4_affine, .q5_affine, .q6_affine, .q8_affine => {
            if (group_size != 32 and group_size != 64 and group_size != 128) return error.InvalidGroupSize;
            if (k % group_size != 0) return error.UnalignedK;
            const bit_width: usize = switch (dtype) {
                .q2_affine => 2,
                .q3_affine => 3,
                .q4_affine => 4,
                .q5_affine => 5,
                .q6_affine => 6,
                .q8_affine => 8,
                else => unreachable,
            };
            const rb = (k * bit_width) / 8;
            const groups = k / group_size;
            const rp = groups * 4;
            if (data.len < n * rb or params.len < n * rp) return error.BufferTooSmall;
            const row_data = data[row_idx * rb ..][0..rb];
            const row_params = params[row_idx * rp ..][0..rp];
            switch (dtype) {
                .q2_affine => try dequantAffineRow(.q2, row_data, row_params, k, group_size, out_row),
                .q3_affine => try dequantAffineRow(.q3, row_data, row_params, k, group_size, out_row),
                .q4_affine => try dequantAffineRow(.q4, row_data, row_params, k, group_size, out_row),
                .q5_affine => try dequantAffineRow(.q5, row_data, row_params, k, group_size, out_row),
                .q6_affine => try dequantAffineRow(.q6, row_data, row_params, k, group_size, out_row),
                .q8_affine => try dequantAffineRow(.q8, row_data, row_params, k, group_size, out_row),
                else => unreachable,
            }
        },
        .fp8_e4m3_block => {
            const total = std.math.mul(usize, n, k) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            const nb_cnt = (n + 127) / 128;
            const kb_cnt = (k + 127) / 128;
            const req_params = nb_cnt * kb_cnt * 4;
            if (params.len < req_params) return error.InvalidParams;
            const row = data[row_idx * k ..][0..k];
            const nb_idx = row_idx / 128;
            for (0..k) |col| {
                const kb_idx = col / 128;
                const sc = readF32(params, (nb_idx * kb_cnt + kb_idx) * 4);
                out_row[col] = e4m3ToF32(row[col]) * sc;
            }
        },
        .fp8_e4m3_row => {
            const total = std.math.mul(usize, n, k) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            if (params.len < n * 4) return error.InvalidParams;
            const sc = readF32(params, row_idx * 4);
            const row = data[row_idx * k ..][0..k];
            for (0..k) |col| out_row[col] = e4m3ToF32(row[col]) * sc;
        },
        .fp8_e4m3_tensor => {
            const total = std.math.mul(usize, n, k) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            const sc: f32 = if (params.len == 4)
                readF32(params, 0)
            else if (params.len == n * 4)
                readF32(params, row_idx * 4)
            else
                return error.InvalidParams;
            const row = data[row_idx * k ..][0..k];
            for (0..k) |col| out_row[col] = e4m3ToF32(row[col]) * sc;
        },
        .mxfp8_g32 => {
            if (k % 32 != 0) return error.UnalignedK;
            const total = std.math.mul(usize, n, k) catch return error.Overflow;
            const groups = k / 32;
            if (data.len < total or params.len < n * groups) return error.BufferTooSmall;
            const row = data[row_idx * k ..][0..k];
            const row_scales = params[row_idx * groups ..][0..groups];
            for (0..groups) |g| {
                const sc = ue8m0ToF32(row_scales[g]);
                for (0..32) |j| {
                    out_row[g * 32 + j] = e4m3ToF32(row[g * 32 + j]) * sc;
                }
            }
        },
        .nvfp4_g16 => {
            if (k % 16 != 0) return error.UnalignedK;
            const rb = k / 2;
            const groups = k / 16;
            const micro_total = std.math.mul(usize, n, groups) catch return error.Overflow;
            const outer_off = align4(micro_total);
            if (data.len < n * rb or params.len < outer_off + 4) return error.BufferTooSmall;
            const outer_scale = readF32(params, outer_off);
            const row = data[row_idx * rb ..][0..rb];
            const row_micros = params[row_idx * groups ..][0..groups];
            for (0..groups) |g| {
                const eff_scale = nvfp4ScaleToF32(row_micros[g]) * outer_scale;
                for (0..8) |j| {
                    const byte = row[g * 8 + j];
                    out_row[g * 16 + 2 * j] = e2m1ToF32(@truncate(byte & 0x0F)) * eff_scale;
                    out_row[g * 16 + 2 * j + 1] = e2m1ToF32(@truncate(byte >> 4)) * eff_scale;
                }
            }
        },
        else => {
            const info = ggufBlockInfo(dtype) orelse return error.UnsupportedDType;
            if (k % info.block_elems != 0) return error.UnalignedK;
            const rb = (k / info.block_elems) * info.block_bytes;
            const total = std.math.mul(usize, n, rb) catch return error.Overflow;
            if (data.len < total) return error.BufferTooSmall;
            try dequantGgufRow(dtype, data[row_idx * rb ..][0..rb], k, out_row);
        },
    }
}

/// CPU `f32` reference GEMV (`y[n] = sum_k x[k] * dequant(W[n, k])`) for any `.amf` `DType`.
pub fn gemvCpuRef(
    dtype: DType,
    x: []const f16,
    data: []const u8,
    params: []const u8,
    n: usize,
    k: usize,
    group_size: u16,
    y: []f32,
) Error!void {
    return gemmCpuRef(dtype, x, data, params, 1, n, k, group_size, y);
}

/// CPU `f32` reference GEMM (`Y[m, n] = sum_k X[m, k] * dequant(W[n, k])`) with
/// caller-provided `row_scratch[0..k]` so arbitrarily wide `k` needs zero heap allocation.
pub fn gemmCpuRefWithScratch(
    dtype: DType,
    x: []const f16,
    data: []const u8,
    params: []const u8,
    m: usize,
    n: usize,
    k: usize,
    group_size: u16,
    y: []f32,
    row_scratch: []f32,
) Error!void {
    if (m == 0 or n == 0 or k == 0) return error.ZeroDimension;
    const x_len = std.math.mul(usize, m, k) catch return error.Overflow;
    const y_len = std.math.mul(usize, m, n) catch return error.Overflow;
    if (x.len < x_len or y.len < y_len or row_scratch.len < k) return error.BufferTooSmall;
    const w_row = row_scratch[0..k];
    for (0..n) |ni| {
        try dequantRowCpuRef(dtype, data, params, n, k, ni, group_size, w_row);
        for (0..m) |mi| {
            const x_row = x[mi * k ..][0..k];
            var acc: f32 = 0.0;
            for (0..k) |ki| {
                acc += @as(f32, @floatCast(x_row[ki])) * w_row[ki];
            }
            y[mi * n + ni] = acc;
        }
    }
}

/// Zero-allocation CPU `f32` reference GEMM for `k <= 32768`.
pub fn gemmCpuRef(
    dtype: DType,
    x: []const f16,
    data: []const u8,
    params: []const u8,
    m: usize,
    n: usize,
    k: usize,
    group_size: u16,
    y: []f32,
) Error!void {
    if (k > 32768) return error.BufferTooSmall;
    var scratch: [32768]f32 = undefined;
    return gemmCpuRefWithScratch(dtype, x, data, params, m, n, k, group_size, y, scratch[0..k]);
}

