// G24: Activation-Quantization Emulation CPU Reference
// ============================================================================

fn quantizeBlockE2M1Mae(x_blk: *const [16]f32, scale: f32, out_blk: *[16]f32) f32 {
    if (scale <= 0.0 or !std.math.isFinite(scale)) {
        @memset(out_blk, 0.0);
        var mae: f32 = 0.0;
        for (x_blk) |v| mae += @abs(v);
        return mae;
    }
    const inv_s = 1.0 / scale;
    var mae: f32 = 0.0;
    for (x_blk, 0..) |v, i| {
        const q = f32ToE2m1(v * inv_s);
        const dq = e2m1ToF32(q) * scale;
        out_blk[i] = dq;
        mae += @abs(v - dq);
    }
    return mae;
}

/// CPU `f32` reference for `G24` activation quant-dequant emulation on `[m, k]`.
pub fn actQuantEmulateF32CpuRef(
    mode: ActQuantMode,
    x: []const f32,
    m: usize,
    k: usize,
    out: []f32,
) Error!void {
    if (m == 0 or k == 0) return error.ZeroDimension;
    const total = std.math.mul(usize, m, k) catch return error.Overflow;
    if (x.len < total or out.len < total) return error.BufferTooSmall;

    switch (mode) {
        .none => @memcpy(out[0..total], x[0..total]),
        .mxfp8_g32 => {
            if (k % 32 != 0) return error.UnalignedK;
            for (0..m) |mi| {
                const xr = x[mi * k ..][0..k];
                const yr = out[mi * k ..][0..k];
                var off: usize = 0;
                while (off < k) : (off += 32) {
                    var amax: f32 = 0.0;
                    for (xr[off..][0..32]) |v| amax = @max(amax, @abs(v));
                    if (amax == 0.0) {
                        @memset(yr[off..][0..32], 0.0);
                        continue;
                    }
                    const raw_exp: i32 = @as(i32, @intFromFloat(@floor(@log2(amax)))) - 8 + 127;
                    const ue: u8 = @intCast(std.math.clamp(raw_exp, 0, 254));
                    const scale = ue8m0ToF32(ue);
                    const inv_s = 1.0 / scale;
                    for (0..32) |j| {
                        yr[off + j] = e4m3ToF32(f32ToE4m3(xr[off + j] * inv_s)) * scale;
                    }
                }
            }
        },
        .fp8_g128 => {
            if (k % 128 != 0) return error.UnalignedK;
            for (0..m) |mi| {
                const xr = x[mi * k ..][0..k];
                const yr = out[mi * k ..][0..k];
                var off: usize = 0;
                while (off < k) : (off += 128) {
                    var amax: f32 = 0.0;
                    for (xr[off..][0..128]) |v| amax = @max(amax, @abs(v));
                    if (amax == 0.0) {
                        @memset(yr[off..][0..128], 0.0);
                        continue;
                    }
                    const scale = amax / 448.0;
                    const inv_s = 1.0 / scale;
                    for (0..128) |j| {
                        yr[off + j] = e4m3ToF32(f32ToE4m3(xr[off + j] * inv_s)) * scale;
                    }
                }
            }
        },
        .nvfp4_g16, .nvfp4_fouroversix_mae => {
            if (k % 16 != 0) return error.UnalignedK;
            for (0..m) |mi| {
                const xr = x[mi * k ..][0..k];
                const yr = out[mi * k ..][0..k];
                var amax_row: f32 = 0.0;
                for (xr) |v| amax_row = @max(amax_row, @abs(v));
                if (amax_row == 0.0) {
                    @memset(yr, 0.0);
                    continue;
                }
                const outer: f32 = amax_row / (448.0 * 6.0);
                var off: usize = 0;
                while (off < k) : (off += 16) {
                    const x_blk: *const [16]f32 = xr[off..][0..16];
                    const y_blk: *[16]f32 = yr[off..][0..16];
                    var b_amax: f32 = 0.0;
                    for (x_blk) |v| b_amax = @max(b_amax, @abs(v));
                    if (b_amax == 0.0) {
                        @memset(y_blk, 0.0);
                        continue;
                    }
                    const d6 = nvfp4ScaleToF32(f32ToE4m3(b_amax / (6.0 * outer))) * outer;
                    var out6: [16]f32 = undefined;
                    const mae6 = quantizeBlockE2M1Mae(x_blk, d6, &out6);
                    if (mode == .nvfp4_fouroversix_mae) {
                        const d4 = nvfp4ScaleToF32(f32ToE4m3(b_amax / (4.0 * outer))) * outer;
                        var out4: [16]f32 = undefined;
                        const mae4 = quantizeBlockE2M1Mae(x_blk, d4, &out4);
                        if (d4 > 0.0 and mae4 < mae6) {
                            y_blk.* = out4;
                            continue;
                        }
                    }
                    y_blk.* = out6;
                }
            }
        },
    }
}

/// CPU `f16` reference for `G24` activation quant-dequant emulation (`ami_act_quant_emulate_f16`).
pub fn actQuantEmulateCpuRef(
    mode: ActQuantMode,
    x: []const f16,
    m: usize,
    k: usize,
    out: []f16,
) Error!void {
    if (m == 0 or k == 0) return error.ZeroDimension;
    const total = std.math.mul(usize, m, k) catch return error.Overflow;
    if (x.len < total or out.len < total) return error.BufferTooSmall;
    if (mode == .none) {
        @memcpy(out[0..total], x[0..total]);
        return;
    }
    if (k > 32768) return error.BufferTooSmall;
    var row_in: [32768]f32 = undefined;
    var row_out: [32768]f32 = undefined;
    for (0..m) |mi| {
        const xr = x[mi * k ..][0..k];
        const yr = out[mi * k ..][0..k];
        for (0..k) |ki| row_in[ki] = @floatCast(xr[ki]);
        try actQuantEmulateF32CpuRef(mode, row_in[0..k], 1, k, row_out[0..k]);
        for (0..k) |ki| yr[ki] = @floatCast(row_out[ki]);
    }
}

