//! Multi-format quantization codecs, GGML block reference decoders, and
//! activation-quantization emulation CPU references (`M8.1`, ADR-0024).
//!
//! Covers:
//! - Generalized MLX affine `q2..q8` (`group_size in {32, 64, 128}`)
//! - FP8 (`fp8_e4m3_block` 128x128, `fp8_e4m3_row`, `fp8_e4m3_tensor`)
//! - OCP `mxfp8_g32` (`E4M3FN` + `UE8M0`)
//! - NVIDIA `nvfp4_g16` (`E2M1` + `E4M3` + trailing `f32` outer scale)
//! - Standard upstream GGUF raw block dtypes (`15..37`, bit-exact to `ggml-quants.c`)
//! - Activation quantization emulation (`G24`: `mxfp8_g32`, `fp8_g128`, `nvfp4_g16`, `nvfp4_fouroversix_mae`)

const std = @import("std");
const spec = @import("spec.zig");
const amf = @import("../format/amf.zig");

pub const DType = amf.DType;

pub const Error = spec.ShapeError || error{
    UnsupportedDType,
    InvalidGroupSize,
    InvalidParams,
    BufferTooSmall,
    OutOfBounds,
};

pub const ActQuantMode = enum(u8) {
    none = 0,
    mxfp8_g32 = 1,
    fp8_g128 = 2,
    nvfp4_g16 = 3,
    nvfp4_fouroversix_mae = 4,
};

pub const AffineQuantBits = enum(u8) {
    q2 = 2,
    q3 = 3,
    q4 = 4,
    q5 = 5,
    q6 = 6,
    q8 = 8,

    pub fn bitWidth(self: AffineQuantBits) u8 {
        return @backingInt(self);
    }
};

pub const AffineSpec = struct {
    bits: AffineQuantBits,
    group_size: u16 = 64,
};

