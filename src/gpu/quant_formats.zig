fn fillSyntheticFormatBuffers(
    dtype: DType,
    group_size: u16,
    n: usize,
    k: usize,
    qweight: []u8,
    params: []u8,
    seed: usize,
) void {
    if (dtype.isAffine()) {
        const eff_gs: usize = dtype.effectiveGroupSize(group_size);
        const bits = dtype.affineBits().?;
        const q_mask: u8 = @intCast((@as(u16, 1) << @intCast(bits)) - 1);
        const grp_bytes = (eff_gs * bits) / 8;
        const grps = k / eff_gs;
        const rb = grps * grp_bytes;
        var codes: [128]u8 = undefined;
        const sb: []ScaleBias = @alignCast(std.mem.bytesAsSlice(ScaleBias, params[0 .. n * grps * @sizeOf(ScaleBias)]));
        for (0..n) |r| {
            for (0..grps) |g| {
                for (0..eff_gs) |j| {
                    codes[j] = @intCast((seed + r * 13 + g * 7 + j * 5 + 3) & q_mask);
                }
                packAffineGroup(bits, @intCast(eff_gs), codes[0..eff_gs], qweight[r * rb + g * grp_bytes ..][0..grp_bytes]);
                const s: f32 = 0.03125 + 0.015625 * @as(f32, @floatFromInt((r + g) % 7));
                const b: f32 = -0.25 - 0.0625 * @as(f32, @floatFromInt((r * 3 + g) % 5));
                sb[r * grps + g] = .{ .scale = @floatCast(s), .bias = @floatCast(b) };
            }
        }
        return;
    }

    if (dtype == .fp8_e4m3_block or dtype == .fp8_e4m3_row or dtype == .fp8_e4m3_tensor) {
        for (0..n) |r| {
            for (0..k) |c| {
                const v = (@as(f32, @floatFromInt(@as(i32, @intCast((seed + r * 11 + c * 7) % 15)) - 7))) * 0.25;
                qweight[r * k + c] = f32ToE4m3(v);
            }
        }
        const sf: []f32 = @alignCast(std.mem.bytesAsSlice(f32, params));
        for (sf, 0..) |*v, idx| {
            v.* = 0.125 + 0.0625 * @as(f32, @floatFromInt((seed + idx) % 6));
        }
        return;
    }

    if (dtype == .mxfp8_g32) {
        const grps = k / 32;
        for (0..n) |r| {
            for (0..k) |c| {
                const v = (@as(f32, @floatFromInt(@as(i32, @intCast((seed + r * 5 + c * 9) % 13)) - 6))) * 0.25;
                qweight[r * k + c] = f32ToE4m3(v);
            }
            for (0..grps) |g| {
                params[r * grps + g] = @intCast(123 + ((seed + r + g) % 6));
            }
        }
        return;
    }

    if (dtype == .nvfp4_g16) {
        const grps = k / 16;
        const rb = k / 2;
        for (0..n) |r| {
            for (0..rb) |b| {
                const lo: u8 = @intCast((seed + r * 7 + b * 3) & 0xF);
                const hi: u8 = @intCast((seed + r * 5 + b * 11 + 1) & 0xF);
                qweight[r * rb + b] = lo | (hi << 4);
            }
            for (0..grps) |g| {
                // Valid positive E4M3 micro-scales in [0.125 .. 1.5]
                const sv: f32 = 0.25 + 0.125 * @as(f32, @floatFromInt((seed + r + g) % 7));
                params[r * grps + g] = f32ToE4m3(sv);
            }
        }
        const outer_off = DType.nvfp4OuterScaleOffset(n, k) catch unreachable;
        const outer_ptr: *align(1) f32 = @ptrCast(params[outer_off..].ptr);
        outer_ptr.* = 0.375;
        return;
    }

    // Standard GGUF block formats: fill blocks deterministically with valid fp16 scales & bit patterns.
    const rb = dtype.rowWeightBytes(k, group_size) catch unreachable;
    const bb = dtype.blockBytes(group_size);
    const blks = dtype.groupsPerRow(k, group_size) catch unreachable;
    for (0..n) |r| {
        for (0..blks) |b| {
            const blk = qweight[r * rb + b * bb ..][0..bb];
            for (blk, 0..) |*byte, i| {
                byte.* = @intCast((seed + r * 29 + b * 17 + i * 13) & 0xFF);
            }
            const d_h: f16 = @floatCast(0.0625 + 0.015625 * @as(f32, @floatFromInt((seed + r + b) % 5)));
            const m_h: f16 = @floatCast(-0.125 - 0.03125 * @as(f32, @floatFromInt((seed + r * 3 + b) % 4)));
            const d_u16: u16 = @bitCast(d_h);
            const m_u16: u16 = @bitCast(m_h);

            switch (dtype) {
                .gguf_q4_0, .gguf_q5_0, .gguf_q8_0, .gguf_iq4_nl, .gguf_q2_0, .gguf_iq1_s, .gguf_iq2_xxs, .gguf_iq2_xs, .gguf_iq2_s, .gguf_iq3_xxs, .gguf_iq3_s, .gguf_iq4_xs => {
                    std.mem.writeInt(u16, blk[0..2], d_u16, .little);
                },
                .gguf_q4_1, .gguf_q5_1, .gguf_q4_k, .gguf_q5_k => {
                    std.mem.writeInt(u16, blk[0..2], d_u16, .little);
                    std.mem.writeInt(u16, blk[2..4], m_u16, .little);
                },
                .gguf_q2_k => {
                    std.mem.writeInt(u16, blk[80..82], d_u16, .little);
                    std.mem.writeInt(u16, blk[82..84], m_u16, .little);
                },
                .gguf_q3_k => {
                    std.mem.writeInt(u16, blk[108..110], d_u16, .little);
                },
                .gguf_q6_k => {
                    std.mem.writeInt(u16, blk[208..210], d_u16, .little);
                },
                .gguf_tq1_0 => {
                    std.mem.writeInt(u16, blk[52..54], d_u16, .little);
                },
                .gguf_tq2_0 => {
                    std.mem.writeInt(u16, blk[64..66], d_u16, .little);
                },
                .gguf_mxfp4 => {
                    blk[0] = @intCast(124 + ((seed + r + b) % 5));
                },
                .gguf_iq1_m => {
                    // Upper 4 bits of each of 4 uint16 scales encode fp16 `d` (0x2C00 = 0.0625).
                    const d_nib = [_]u16{ (d_u16 & 0x000F) << 12, (d_u16 & 0x00F0) << 8, (d_u16 & 0x0F00) << 4, d_u16 & 0xF000 };
                    for (0..4) |s_i| {
                        const lo12: u16 = @intCast((seed + r + b + s_i * 3) & 0x0FFF);
                        std.mem.writeInt(u16, blk[48 + s_i * 2 ..][0..2], lo12 | d_nib[s_i], .little);
                    }
                },
                else => unreachable,
            }
        }
    }
}

fn fillSyntheticF16(buf: []f16, seed: usize) void {
    for (buf, 0..) |*v, idx| {
        const c: i32 = @as(i32, @intCast((seed + idx * 17 + 11) % 29)) - 14;
        v.* = @floatCast(@as(f32, @floatFromInt(c)) * 0.0625);
    }
}

fn verifyFormatParity(
    device: metal.Device,
    pipes: *const QuantFormatPipelines,
    compute: *metal.Compute,
    dtype: DType,
    group_size: u16,
    m_batch: usize,
    n: usize,
    k: usize,
    with_residual: bool,
    verify_tile_f16: bool,
) !void {
    const gpa = std.testing.allocator;
    const w_bytes = try dtype.packedWeightBytes(n, k, group_size);
    const p_bytes = try dtype.paramsBytes(n, k, group_size);
    const w_off: usize = 0;
    const p_off: usize = align64(w_bytes);
    const x_off: usize = align64(p_off + p_bytes);
    const x_bytes: usize = m_batch * k * @sizeOf(f16);
    const res_off: usize = align64(x_off + x_bytes);
    const y_bytes: usize = m_batch * n * @sizeOf(f16);
    const y1_off: usize = align64(res_off + y_bytes);
    const yb_off: usize = align64(y1_off + align64(n * @sizeOf(f16)));
    const tile_off: usize = align64(yb_off + y_bytes);
    const tile_bytes: usize = n * k * @sizeOf(f16);
    const total = try page.alignUp(tile_off + tile_bytes + 64);

    const region = try page.WiredRegion.init(total);
    defer region.deinit();
    @memset(region.bytes, 0);

    const qweight = region.bytes[w_off..][0..w_bytes];
    const params = region.bytes[p_off..][0..p_bytes];
    const x_f16: []f16 = @alignCast(std.mem.bytesAsSlice(f16, region.bytes[x_off..][0..x_bytes]));
    const res_f16: []f16 = @alignCast(std.mem.bytesAsSlice(f16, region.bytes[res_off..][0..y_bytes]));
    const y1_f16: []f16 = @alignCast(std.mem.bytesAsSlice(f16, region.bytes[y1_off..][0 .. n * @sizeOf(f16)]));
    const yb_f16: []f16 = @alignCast(std.mem.bytesAsSlice(f16, region.bytes[yb_off..][0..y_bytes]));
    const tile_f16: []f16 = @alignCast(std.mem.bytesAsSlice(f16, region.bytes[tile_off..][0..tile_bytes]));

    const dtype_u32: u32 = @backingInt(dtype);
    fillSyntheticFormatBuffers(dtype, group_size, n, k, qweight, params, dtype_u32 * 13 + group_size);
    fillSyntheticF16(x_f16, dtype_u32 * 7 + 3);
    fillSyntheticF16(res_f16, dtype_u32 * 19 + 5);

    const ref_m1 = try gpa.alloc(f32, n);
    defer gpa.free(ref_m1);
    const ref_mb = try gpa.alloc(f32, m_batch * n);
    defer gpa.free(ref_mb);
    try matmulCpuRef(gpa, dtype, group_size, x_f16[0..k], qweight, params, if (with_residual) res_f16[0..n] else null, ref_m1, 1, n, k);
    try matmulCpuRef(gpa, dtype, group_size, x_f16, qweight, params, if (with_residual) res_f16 else null, ref_mb, m_batch, n, k);

    const gpu_buf = try metal.Buffer.wrap(device, region.bytes);
    defer gpu_buf.close();
    try compute.makeResident(&.{gpu_buf});
    defer {
        compute.removeResident(&.{gpu_buf}) catch |err| std.debug.panic("removeResident failed: {}", .{err});
    }

    const p_bind: ?metal.BufferBinding = if (p_bytes > 0) .{ .buffer = gpu_buf, .offset = p_off } else null;

    var frame = try compute.beginFrame(5000);
    errdefer frame.abort();
    try pipes.encodeGemv(&frame, dtype, group_size, .{
        .x = .{ .buffer = gpu_buf, .offset = x_off },
        .qweight = .{ .buffer = gpu_buf, .offset = w_off },
        .params = p_bind,
        .y = .{ .buffer = gpu_buf, .offset = y1_off },
        .residual = if (with_residual) .{ .buffer = gpu_buf, .offset = res_off } else null,
        .n = @intCast(n),
        .k = @intCast(k),
    }, false);
    try pipes.encodeGemvBatch(&frame, dtype, group_size, .{
        .x = .{ .buffer = gpu_buf, .offset = x_off },
        .qweight = .{ .buffer = gpu_buf, .offset = w_off },
        .params = p_bind,
        .y = .{ .buffer = gpu_buf, .offset = yb_off },
        .residual = if (with_residual) .{ .buffer = gpu_buf, .offset = res_off } else null,
        .m = @intCast(m_batch),
        .n = @intCast(n),
        .k = @intCast(k),
    }, true);
    if (verify_tile_f16) {
        try pipes.encodeDequantTileF16(&frame, dtype, group_size, .{
            .qweight = .{ .buffer = gpu_buf, .offset = w_off },
            .params = p_bind,
            .dst_f16 = .{ .buffer = gpu_buf, .offset = tile_off },
            .n_total = @intCast(n),
            .k_total = @intCast(k),
            .tile_n = @intCast(n),
            .tile_k = @intCast(k),
        }, true);
    }
    const sig = try frame.commit();
    try compute.wait(sig, 5000);

    for (ref_m1, 0..) |expected, idx| {
        const got: f32 = @floatCast(y1_f16[idx]);
        const tol: f32 = @max(0.015, @abs(expected) * 0.004);
        try std.testing.expectApproxEqAbs(expected, got, tol);
    }
    for (ref_mb, 0..) |expected, idx| {
        const got: f32 = @floatCast(yb_f16[idx]);
        const tol: f32 = @max(0.015, @abs(expected) * 0.004);
        try std.testing.expectApproxEqAbs(expected, got, tol);
    }
    if (verify_tile_f16) {
        const row_ref = try gpa.alloc(f32, k);
        defer gpa.free(row_ref);
        for (0..n) |r| {
            try dequantRowCpuRef(dtype, group_size, qweight, params, r, n, k, row_ref);
            for (0..k) |c| {
                const expected = row_ref[c];
                const got: f32 = @floatCast(tile_f16[r * k + c]);
                const tol: f32 = @max(0.004, @abs(expected) * 0.002);
                try std.testing.expectApproxEqAbs(expected, got, tol);
            }
        }
    }
}

