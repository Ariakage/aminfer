    min_working_set_bytes: usize = 64 * 1024 * 1024,
    warmup_batches: u32 = 4,
    timed_batches: u32 = 8,
    dispatches_per_batch: u32 = 32,
    spec_bus_gbs: f64 = 120.0,
    timeout_ms: u64 = 30_000,
};

pub const GemvBandwidthResult = struct {
    dtype: DType,
    group_size: u16,
    n: u32,
    k: u32,
    bytes_per_dispatch: u64,
    dispatches: u64,
    weight_slots: usize,
    elapsed_ns: u64,
    spec_bus_gbs: f64,

    pub fn avgLatencyUs(self: GemvBandwidthResult) f64 {
        if (self.dispatches == 0) return 0.0;
        return (@as(f64, @floatFromInt(self.elapsed_ns)) / @as(f64, @floatFromInt(self.dispatches))) / 1000.0;
    }

    pub fn bandwidthGbs(self: GemvBandwidthResult) f64 {
        if (self.elapsed_ns == 0) return 0.0;
        const total_bytes: f64 = @as(f64, @floatFromInt(self.bytes_per_dispatch)) * @as(f64, @floatFromInt(self.dispatches));
        return total_bytes / @as(f64, @floatFromInt(self.elapsed_ns));
    }

    pub fn busUtilizationPct(self: GemvBandwidthResult) f64 {
        if (self.spec_bus_gbs <= 0.0) return 0.0;
        return (self.bandwidthGbs() / self.spec_bus_gbs) * 100.0;
    }
};

fn monotonicNowNs() error{ClockFailed}!u64 {
    var ts: std.c.timespec = undefined;
    if (std.c.clock_gettime(std.c.CLOCK.UPTIME_RAW, &ts) != 0) {
        return error.ClockFailed;
    }
    if (ts.sec < 0 or ts.nsec < 0) return error.ClockFailed;
    return @as(u64, @intCast(ts.sec)) * std.time.ns_per_s + @as(u64, @intCast(ts.nsec));
}

pub const BenchError = InitError || EncodeError || error{ClockFailed};

/// Measures `M = 1` register-dequant GEMV effective DRAM bandwidth (GB/s) over
/// rotating 16 KiB-aligned wired weight slots (`>= min_working_set_bytes`).
pub fn measureGemvBandwidthGbs(
    device: metal.Device,
    library: metal.Library,
    existing_pipes: ?*const QuantFormatPipelines,
    cfg: GemvBandwidthConfig,
) BenchError!GemvBandwidthResult {
    const spec = FormatSpec.normalized(cfg.dtype, cfg.group_size);
    try spec.dtype.validateShape(cfg.n, cfg.k, spec.group_size);

    var owned_pipes: ?QuantFormatPipelines = null;
    defer if (owned_pipes) |*p| p.close();
    const pipes: *const QuantFormatPipelines = existing_pipes orelse blk: {
        owned_pipes = try QuantFormatPipelines.initWithOptions(device, library, .{
            .specs = &.{spec},
            .include_moe = false,
            .include_act_quant = false,
        });
        break :blk &owned_pipes.?;
    };

    const w_bytes = try spec.dtype.packedWeightBytes(cfg.n, cfg.k, spec.group_size);
    const p_bytes = try spec.dtype.paramsBytes(cfg.n, cfg.k, spec.group_size);
    const w_stride = align64(w_bytes);
    const p_stride = align64(p_bytes);
    const slot_bytes = w_stride + p_stride;
    const x_bytes = align64(@as(usize, cfg.k) * @sizeOf(f16));
    const y_bytes = align64(@as(usize, cfg.n) * @sizeOf(f16));

    const min_slots: usize = if (cfg.min_working_set_bytes == 0) 1 else @max(@as(usize, 1), (cfg.min_working_set_bytes + slot_bytes - 1) / slot_bytes);
    const total_region = try page.alignUp(min_slots * slot_bytes + x_bytes + y_bytes);
    const region = try page.WiredRegion.init(total_region);
    defer region.deinit();

    // Deterministic non-zero fill so weights and activations are finite and valid.
    for (region.bytes, 0..) |*b, idx| {
        b.* = @intCast((idx * 37 + 13) & 0x3F);
    }
    const x_off: usize = min_slots * slot_bytes;
    const y_off: usize = x_off + x_bytes;
    const x_f16: []f16 = @alignCast(std.mem.bytesAsSlice(f16, region.bytes[x_off .. x_off + @as(usize, cfg.k) * @sizeOf(f16)]));
    for (x_f16, 0..) |*v, idx| {
        v.* = @floatCast(@as(f32, @floatFromInt(@as(i32, @intCast(idx % 17)) - 8)) * 0.0625);
    }
    if (p_bytes > 0) {
        for (0..min_slots) |s| {
            const p_slice = region.bytes[s * slot_bytes + w_stride ..][0..p_bytes];
            if (spec.dtype.isAffine()) {
                const sb: []ScaleBias = @alignCast(std.mem.bytesAsSlice(ScaleBias, p_slice));
                for (sb) |*item| item.* = .{ .scale = @floatCast(0.0625), .bias = @floatCast(-0.125) };
            } else if (spec.dtype == .fp8_e4m3_block or spec.dtype == .fp8_e4m3_row or spec.dtype == .fp8_e4m3_tensor) {
                const sf: []f32 = @alignCast(std.mem.bytesAsSlice(f32, p_slice));
                for (sf) |*v| v.* = 0.0625;
            } else if (spec.dtype == .mxfp8_g32) {
                @memset(p_slice, 125);
            } else if (spec.dtype == .nvfp4_g16) {
                const outer_off = try DType.nvfp4OuterScaleOffset(cfg.n, cfg.k);
                @memset(p_slice[0..outer_off], 0x38); // 1.0 in E4M3
                const outer_ptr: *align(1) f32 = @ptrCast(p_slice[outer_off..].ptr);
                outer_ptr.* = 0.0625;
            }
        }
    }

    const gpu_buf = try metal.Buffer.wrap(device, region.bytes);
    defer gpu_buf.close();

    var compute = try metal.Compute.initWithFrames(device, 2);
    defer compute.close();
    try compute.makeResident(&.{gpu_buf});
    if (spec.dtype.needsCodebook()) {
        try pipes.makeResident(compute);
    }

    var cursor: usize = 0;
    var warm_sig: u64 = 0;
    for (0..cfg.warmup_batches) |_| {
        var frame = try compute.beginFrame(cfg.timeout_ms);
        errdefer frame.abort();
        for (0..cfg.dispatches_per_batch) |d| {
            const slot = cursor % min_slots;
            cursor += 1;
            const w_off: u64 = @intCast(slot * slot_bytes);
            const p_off: u64 = w_off + w_stride;
            try pipes.encodeGemv(&frame, spec.dtype, spec.group_size, .{
                .x = .{ .buffer = gpu_buf, .offset = x_off },
                .qweight = .{ .buffer = gpu_buf, .offset = w_off },
                .params = if (p_bytes > 0) .{ .buffer = gpu_buf, .offset = p_off } else null,
                .y = .{ .buffer = gpu_buf, .offset = y_off },
                .n = cfg.n,
                .k = cfg.k,
            }, d > 0);
        }
        warm_sig = try frame.commit();
    }
    if (cfg.warmup_batches > 0) {
        try compute.wait(warm_sig, cfg.timeout_ms);
    }

    var last_sig: u64 = 0;
    const t0 = try monotonicNowNs();
    for (0..cfg.timed_batches) |_| {
        var frame = try compute.beginFrame(cfg.timeout_ms);
        errdefer frame.abort();
        for (0..cfg.dispatches_per_batch) |d| {
            const slot = cursor % min_slots;
            cursor += 1;
            const w_off: u64 = @intCast(slot * slot_bytes);
            const p_off: u64 = w_off + w_stride;
            try pipes.encodeGemv(&frame, spec.dtype, spec.group_size, .{
                .x = .{ .buffer = gpu_buf, .offset = x_off },
                .qweight = .{ .buffer = gpu_buf, .offset = w_off },
                .params = if (p_bytes > 0) .{ .buffer = gpu_buf, .offset = p_off } else null,
                .y = .{ .buffer = gpu_buf, .offset = y_off },
                .n = cfg.n,
                .k = cfg.k,
            }, d > 0);
        }
        last_sig = try frame.commit();
    }
    try compute.wait(last_sig, cfg.timeout_ms);
    const t1 = try monotonicNowNs();

    const bytes_per_dispatch: u64 = @as(u64, w_bytes) + p_bytes + @as(u64, cfg.k) * @sizeOf(f16) + @as(u64, cfg.n) * @sizeOf(f16);
    return .{
        .dtype = spec.dtype,
        .group_size = spec.group_size,
        .n = cfg.n,
        .k = cfg.k,
        .bytes_per_dispatch = bytes_per_dispatch,
        .dispatches = @as(u64, cfg.timed_batches) * cfg.dispatches_per_batch,
        .weight_slots = min_slots,
        .elapsed_ns = t1 - t0,
        .spec_bus_gbs = cfg.spec_bus_gbs,
    };
}

