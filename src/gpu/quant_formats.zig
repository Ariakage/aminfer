/// Decodes OCP FP8 `E4M3FN` (`0x7F`/`0xFF` -> `NaN`) to `f32`.
pub fn e4m3ToF32(b: u8) f32 {
    const ax: u8 = b & 0x7F;
    if (ax == 0x7F) return std.math.nan(f32);
    const exp4: u32 = (ax >> 3) & 0xF;
    const man3: u32 = ax & 0x7;
    const mag: f32 = if (exp4 == 0)
        @as(f32, @floatFromInt(man3)) * (1.0 / 512.0)
    else
        @bitCast(((exp4 + 120) << 23) | (man3 << 20));
    return @bitCast(@as(u32, @bitCast(mag)) | (@as(u32, b & 0x80) << 24));
}

/// Decodes `E4M3` micro-scale (`0x00`/`0x7F`/`0xFF` -> `0.0`) to `f32`.
pub fn e4m3ScaleToF32(b: u8) f32 {
    const ax: u8 = b & 0x7F;
    if (ax == 0 or ax == 0x7F) return 0.0;
    const exp4: u32 = (ax >> 3) & 0xF;
    const man3: u32 = ax & 0x7;
    const mag: f32 = if (exp4 == 0)
        @as(f32, @floatFromInt(man3)) * (1.0 / 512.0)
    else
        @bitCast(((exp4 + 120) << 23) | (man3 << 20));
    return @bitCast(@as(u32, @bitCast(mag)) | (@as(u32, b & 0x80) << 24));
}

/// Encodes `f32` to OCP FP8 `E4M3FN` with RNE and saturation at `+-448.0`.
pub fn f32ToE4m3(x: f32) u8 {
    if (std.math.isNan(x)) return 0;
    const bits: u32 = @bitCast(x);
    const sign_bit: u8 = @intCast((bits >> 31) & 1);
    const a = @abs(x);
    if (a == 0.0) return 0;
    if (a >= 448.0) return (sign_bit << 7) | 0x7E;
    if (a < (1.0 / 64.0)) {
        const scaled = a * 512.0;
        const q_floor: u32 = @intFromFloat(@floor(scaled));
        const frac = scaled - @as(f32, @floatFromInt(q_floor));
        var q = q_floor;
        if (frac > 0.5 or (frac == 0.5 and (q_floor & 1) != 0)) {
            q += 1;
        }
        if (q == 0) return 0;
        if (q >= 8) return (sign_bit << 7) | (1 << 3);
        return (sign_bit << 7) | @as(u8, @intCast(q));
    }
    const abs_bits: u32 = @bitCast(a);
    const f_exp: i32 = @as(i32, @intCast((abs_bits >> 23) & 0xFF)) - 127;
    const f_mant: u32 = abs_bits & 0x7FFFFF;
    var m3: u32 = f_mant >> 20;
    const rem: u32 = f_mant & 0xFFFFF;
    var e4: u32 = @intCast(f_exp + 7);
    if (rem > 0x80000 or (rem == 0x80000 and (m3 & 1) != 0)) {
        m3 += 1;
        if (m3 == 8) {
            m3 = 0;
            e4 += 1;
        }
    }
    if (e4 > 15 or (e4 == 15 and m3 >= 7)) {
        e4 = 15;
        m3 = 6;
    }
    return (sign_bit << 7) | @as(u8, @intCast(e4 << 3)) | @as(u8, @intCast(m3));
}

/// Decodes OCP MX `UE8M0` (`255 -> NaN`, `0 -> 2^-127`, else `2^(e-127)`).
pub fn ue8m0ToF32(e: u8) f32 {
    if (e == 255) return std.math.nan(f32);
    if (e == 0) return @bitCast(@as(u32, 0x00400000));
    return @bitCast(@as(u32, e) << 23);
}

/// Decodes signed 4-bit `E2M1` nibble to `f32`.
pub fn e2m1ToF32(nib: u4) f32 {
    const lut = [8]f32{ 0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0 };
    const mag = nib & 0x7;
    const v = lut[mag];
    return if ((nib & 0x8) != 0 and mag != 0) -v else v;
}

/// Encodes `f32` to signed 4-bit `E2M1` with RNE.
pub fn f32ToE2m1(x: f32) u4 {
    if (std.math.isNan(x)) return 0;
    const neg = x < 0.0;
    const a = @abs(x);
    const mag: u4 = if (a <= 0.25)
        0
    else if (a < 0.75)
        1
    else if (a <= 1.25)
        2
    else if (a < 1.75)
        3
    else if (a <= 2.50)
        4
    else if (a < 3.50)
        5
    else if (a <= 5.00)
        6
    else
        7;
    if (mag == 0) return 0;
    return if (neg) (mag | 0x8) else mag;
}

/// Packs one group of `group_size` MLX-affine codes (`bits in {2,3,4,5,6,8}`).
pub fn packAffineGroup(bits: u8, group_size: u16, codes: []const u8, out: []u8) void {
    const gs: usize = group_size;
    std.debug.assert(codes.len >= gs);
    std.debug.assert(out.len >= (gs * bits) / 8);
    switch (bits) {
        2 => {
            for (0..gs / 4) |i| {
                out[i] = (codes[4 * i] & 0x3) |
                    ((codes[4 * i + 1] & 0x3) << 2) |
                    ((codes[4 * i + 2] & 0x3) << 4) |
                    ((codes[4 * i + 3] & 0x3) << 6);
            }
        },
        3 => {
            for (0..gs / 8) |blk| {
                const c = codes[blk * 8 ..][0..8];
                const w: u24 = @as(u24, c[0] & 7) |
                    (@as(u24, c[1] & 7) << 3) |
                    (@as(u24, c[2] & 7) << 6) |
                    (@as(u24, c[3] & 7) << 9) |
                    (@as(u24, c[4] & 7) << 12) |
                    (@as(u24, c[5] & 7) << 15) |
                    (@as(u24, c[6] & 7) << 18) |
                    (@as(u24, c[7] & 7) << 21);
                out[blk * 3 + 0] = @truncate(w);
                out[blk * 3 + 1] = @truncate(w >> 8);
                out[blk * 3 + 2] = @truncate(w >> 16);
            }
        },
        4 => {
            for (0..gs / 2) |i| {
                out[i] = (codes[2 * i] & 0xF) | ((codes[2 * i + 1] & 0xF) << 4);
            }
        },
        5 => {
            for (0..gs / 8) |blk| {
                const c = codes[blk * 8 ..][0..8];
                const w: u40 = @as(u40, c[0] & 0x1F) |
                    (@as(u40, c[1] & 0x1F) << 5) |
                    (@as(u40, c[2] & 0x1F) << 10) |
                    (@as(u40, c[3] & 0x1F) << 15) |
                    (@as(u40, c[4] & 0x1F) << 20) |
                    (@as(u40, c[5] & 0x1F) << 25) |
                    (@as(u40, c[6] & 0x1F) << 30) |
                    (@as(u40, c[7] & 0x1F) << 35);
                for (0..5) |b| {
                    out[blk * 5 + b] = @truncate(w >> @intCast(b * 8));
                }
            }
        },
        6 => {
            for (0..gs / 4) |blk| {
                const c = codes[blk * 4 ..][0..4];
                const w: u24 = @as(u24, c[0] & 0x3F) |
                    (@as(u24, c[1] & 0x3F) << 6) |
                    (@as(u24, c[2] & 0x3F) << 12) |
                    (@as(u24, c[3] & 0x3F) << 18);
                out[blk * 3 + 0] = @truncate(w);
                out[blk * 3 + 1] = @truncate(w >> 8);
                out[blk * 3 + 2] = @truncate(w >> 16);
            }
        },
        8 => {
            @memcpy(out[0..gs], codes[0..gs]);
        },
        else => unreachable,
    }
}

inline fn readU16(bytes: []const u8) u16 {
    return std.mem.readInt(u16, bytes[0..2], .little);
}

inline fn readU32(bytes: []const u8) u32 {
    return std.mem.readInt(u32, bytes[0..4], .little);
}

inline fn readF16AsF32(bytes: []const u8) f32 {
    return @floatCast(@as(f16, @bitCast(readU16(bytes))));
}

inline fn readF32(bytes: []const u8) f32 {
    return @bitCast(readU32(bytes));
}

inline fn getScaleMinK4(j: usize, q: []const u8) struct { sc: u8, min: u8 } {
    if (j < 4) {
        return .{ .sc = q[j] & 63, .min = q[j + 4] & 63 };
    }
    return .{
        .sc = (q[j + 4] & 0xF) | ((q[j - 4] >> 6) << 4),
        .min = (q[j + 4] >> 4) | ((q[j] >> 6) << 4),
    };
}

pub const CpuRefError = ShapeError || error{BufferTooSmall};

/// Bit-exact `f32` CPU reference row decoder for all 32 formats (`2,3,6..37`).
pub fn dequantRowCpuRef(
    dtype: DType,
    group_size: u16,
    qweight: []const u8,
    params: []const u8,
    row: usize,
    n: usize,
    k: usize,
    out_f32: []f32,
) CpuRefError!void {
    try dtype.validateShape(n, k, group_size);
    if (row >= n) return error.BufferTooSmall;
    if (out_f32.len < k) return error.BufferTooSmall;
    const rb = try dtype.rowWeightBytes(k, group_size);
    if (qweight.len < n * rb) return error.BufferTooSmall;
    const w_row = qweight[row * rb ..][0..rb];

    if (dtype.isAffine()) {
        const eff_gs: usize = dtype.effectiveGroupSize(group_size);
        const bits = dtype.affineBits().?;
        const grp_bytes = (eff_gs * bits) / 8;
        const grps = k / eff_gs;
        const req_params = n * grps * @sizeOf(ScaleBias);
        if (params.len < req_params) return error.BufferTooSmall;

        for (0..grps) |g| {
            const p_off = (row * grps + g) * @sizeOf(ScaleBias);
            const scale = readF16AsF32(params[p_off .. p_off + 2]);
            const bias = readF16AsF32(params[p_off + 2 .. p_off + 4]);
            const gp = w_row[g * grp_bytes ..][0..grp_bytes];
            const dst = out_f32[g * eff_gs ..][0..eff_gs];
            switch (bits) {
                2 => for (0..eff_gs / 4) |i| {
                    const b = gp[i];
                    dst[4 * i + 0] = @as(f32, @floatFromInt(b & 3)) * scale + bias;
                    dst[4 * i + 1] = @as(f32, @floatFromInt((b >> 2) & 3)) * scale + bias;
                    dst[4 * i + 2] = @as(f32, @floatFromInt((b >> 4) & 3)) * scale + bias;
                    dst[4 * i + 3] = @as(f32, @floatFromInt((b >> 6) & 3)) * scale + bias;
                },
                3 => for (0..eff_gs / 8) |blk| {
                    const w: u24 = @as(u24, gp[blk * 3]) | (@as(u24, gp[blk * 3 + 1]) << 8) | (@as(u24, gp[blk * 3 + 2]) << 16);
                    inline for (0..8) |j| {
                        const q: u8 = @intCast((w >> @intCast(j * 3)) & 7);
                        dst[blk * 8 + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                    }
                },
                4 => for (0..eff_gs / 2) |i| {
                    const b = gp[i];
                    dst[2 * i + 0] = @as(f32, @floatFromInt(b & 0xF)) * scale + bias;
                    dst[2 * i + 1] = @as(f32, @floatFromInt(b >> 4)) * scale + bias;
                },
                5 => for (0..eff_gs / 8) |blk| {
                    var w: u40 = 0;
                    for (0..5) |b| w |= @as(u40, gp[blk * 5 + b]) << @intCast(b * 8);
                    inline for (0..8) |j| {
                        const q: u8 = @intCast((w >> @intCast(j * 5)) & 0x1F);
                        dst[blk * 8 + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                    }
                },
                6 => for (0..eff_gs / 4) |blk| {
                    const w: u24 = @as(u24, gp[blk * 3]) | (@as(u24, gp[blk * 3 + 1]) << 8) | (@as(u24, gp[blk * 3 + 2]) << 16);
                    inline for (0..4) |j| {
                        const q: u8 = @intCast((w >> @intCast(j * 6)) & 0x3F);
                        dst[blk * 4 + j] = @as(f32, @floatFromInt(q)) * scale + bias;
                    }
                },
                8 => for (0..eff_gs) |i| {
                    dst[i] = @as(f32, @floatFromInt(gp[i])) * scale + bias;
                },
                else => unreachable,
            }
        }
        return;
    }

    switch (dtype) {
        .fp8_e4m3_block => {
            const nb = (n + 127) / 128;
            const kb = (k + 127) / 128;
            if (params.len < nb * kb * 4) return error.BufferTooSmall;
            const rb_idx = row / 128;
            for (0..k) |c| {
                const sc = readF32(params[(rb_idx * kb + c / 128) * 4 ..]);
                out_f32[c] = e4m3ToF32(w_row[c]) * sc;
            }
        },
        .fp8_e4m3_row => {
            if (params.len < n * 4) return error.BufferTooSmall;
            const sc = readF32(params[row * 4 ..]);
            for (0..k) |c| out_f32[c] = e4m3ToF32(w_row[c]) * sc;
        },
        .fp8_e4m3_tensor => {
            if (params.len < 4) return error.BufferTooSmall;
            const per_row = (params.len >= n * 4 and n > 1);
            const sc = readF32(params[if (per_row) row * 4 else 0..]);
            for (0..k) |c| out_f32[c] = e4m3ToF32(w_row[c]) * sc;
        },
        .mxfp8_g32 => {
            const grps = k / 32;
            if (params.len < n * grps) return error.BufferTooSmall;
            for (0..grps) |g| {
                const sc = ue8m0ToF32(params[row * grps + g]);
                for (0..32) |j| out_f32[g * 32 + j] = e4m3ToF32(w_row[g * 32 + j]) * sc;
            }
        },
        .nvfp4_g16 => {
            const grps = k / 16;
            const outer_off = try DType.nvfp4OuterScaleOffset(n, k);
            if (params.len < outer_off + 4) return error.BufferTooSmall;
            const outer = readF32(params[outer_off..]);
            for (0..grps) |g| {
                const sc = e4m3ScaleToF32(params[row * grps + g]) * outer;
                for (0..8) |b| {
                    const byte = w_row[g * 8 + b];
                    out_f32[g * 16 + b * 2 + 0] = e2m1ToF32(@truncate(byte & 0xF)) * sc;
                    out_f32[g * 16 + b * 2 + 1] = e2m1ToF32(@truncate(byte >> 4)) * sc;
                }
            }
        },
        .gguf_q4_0 => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 18 ..][0..18];
                const d = readF16AsF32(blk[0..2]);
                for (0..16) |j| {
                    out_f32[b * 32 + j + 0] = @as(f32, @floatFromInt(@as(i32, blk[2 + j] & 0xF) - 8)) * d;
                    out_f32[b * 32 + j + 16] = @as(f32, @floatFromInt(@as(i32, blk[2 + j] >> 4) - 8)) * d;
                }
            }
        },
        .gguf_q4_1 => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 20 ..][0..20];
                const d = readF16AsF32(blk[0..2]);
                const m = readF16AsF32(blk[2..4]);
                for (0..16) |j| {
                    out_f32[b * 32 + j + 0] = @as(f32, @floatFromInt(blk[4 + j] & 0xF)) * d + m;
                    out_f32[b * 32 + j + 16] = @as(f32, @floatFromInt(blk[4 + j] >> 4)) * d + m;
                }
            }
        },
        .gguf_q5_0 => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 22 ..][0..22];
                const d = readF16AsF32(blk[0..2]);
                const qh = readU32(blk[2..6]);
                for (0..16) |j| {
                    const xh0: u8 = @intCast(((qh >> @intCast(j)) << 4) & 0x10);
                    const xh1: u8 = @intCast((qh >> @intCast(j + 12)) & 0x10);
                    const x0: i32 = @as(i32, (blk[6 + j] & 0xF) | xh0) - 16;
                    const x1: i32 = @as(i32, (blk[6 + j] >> 4) | xh1) - 16;
                    out_f32[b * 32 + j + 0] = @as(f32, @floatFromInt(x0)) * d;
                    out_f32[b * 32 + j + 16] = @as(f32, @floatFromInt(x1)) * d;
                }
            }
        },
        .gguf_q5_1 => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 24 ..][0..24];
                const d = readF16AsF32(blk[0..2]);
                const m = readF16AsF32(blk[2..4]);
                const qh = readU32(blk[4..8]);
                for (0..16) |j| {
                    const xh0: u8 = @intCast(((qh >> @intCast(j)) << 4) & 0x10);
                    const xh1: u8 = @intCast((qh >> @intCast(j + 12)) & 0x10);
                    out_f32[b * 32 + j + 0] = @as(f32, @floatFromInt((blk[8 + j] & 0xF) | xh0)) * d + m;
                    out_f32[b * 32 + j + 16] = @as(f32, @floatFromInt((blk[8 + j] >> 4) | xh1)) * d + m;
                }
            }
        },
        .gguf_q8_0 => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 34 ..][0..34];
                const d = readF16AsF32(blk[0..2]);
                for (0..32) |j| {
                    const q: i8 = @bitCast(blk[2 + j]);
                    out_f32[b * 32 + j] = @as(f32, @floatFromInt(q)) * d;
                }
            }
        },
        .gguf_iq4_nl => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 18 ..][0..18];
                const d = readF16AsF32(blk[0..2]);
                for (0..16) |j| {
                    out_f32[b * 32 + j + 0] = @as(f32, @floatFromInt(KVALUES_IQ4NL[blk[2 + j] & 0xF])) * d;
                    out_f32[b * 32 + j + 16] = @as(f32, @floatFromInt(KVALUES_IQ4NL[blk[2 + j] >> 4])) * d;
                }
            }
        },
        .gguf_mxfp4 => {
            for (0..k / 32) |b| {
                const blk = w_row[b * 17 ..][0..17];
                const d = ue8m0ToF32(blk[0]);
                for (0..16) |j| {
                    out_f32[b * 32 + j + 0] = e2m1ToF32(@truncate(blk[1 + j] & 0xF)) * d;
                    out_f32[b * 32 + j + 16] = e2m1ToF32(@truncate(blk[1 + j] >> 4)) * d;
                }
            }
        },
        .gguf_q2_0 => {
            for (0..k / 64) |b| {
                const blk = w_row[b * 18 ..][0..18];
                const d = readF16AsF32(blk[0..2]);
                for (0..64) |j| {
                    const q: i32 = @intCast((blk[2 + j / 4] >> @intCast((j % 4) * 2)) & 3);
                    out_f32[b * 64 + j] = @as(f32, @floatFromInt(q - 1)) * d;
                }
            }
        },
        .gguf_q2_k => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 84 ..][0..84];
                const scales = blk[0..16];
                const qs = blk[16..80];
                const d = readF16AsF32(blk[80..82]);
                const dmin = readF16AsF32(blk[82..84]);
                var y_idx: usize = sb * 256;
                var is: usize = 0;
                var q_off: usize = 0;
                for (0..2) |_| {
                    var shift: u3 = 0;
                    for (0..4) |_| {
                        const sc0 = scales[is];
                        is += 1;
                        const dl0 = d * @as(f32, @floatFromInt(sc0 & 0xF));
                        const ml0 = dmin * @as(f32, @floatFromInt(sc0 >> 4));
                        for (0..16) |l| {
                            out_f32[y_idx] = dl0 * @as(f32, @floatFromInt((qs[q_off + l] >> shift) & 3)) - ml0;
                            y_idx += 1;
                        }
                        const sc1 = scales[is];
                        is += 1;
                        const dl1 = d * @as(f32, @floatFromInt(sc1 & 0xF));
                        const ml1 = dmin * @as(f32, @floatFromInt(sc1 >> 4));
                        for (0..16) |l| {
                            out_f32[y_idx] = dl1 * @as(f32, @floatFromInt((qs[q_off + 16 + l] >> shift) & 3)) - ml1;
                            y_idx += 1;
                        }
                        shift +%= 2;
                    }
                    q_off += 32;
                }
            }
        },
        .gguf_q3_k => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 110 ..][0..110];
                const hm = blk[0..32];
                const qs = blk[32..96];
                const sc_raw = blk[96..108];
                const d_all = readF16AsF32(blk[108..110]);
                const sc0 = readU32(sc_raw[0..4]);
                const sc1 = readU32(sc_raw[4..8]);
                const sc2 = readU32(sc_raw[8..12]);
                const aux = [4]u32{
                    (sc0 & 0x0F0F0F0F) | ((sc2 & 0x03030303) << 4),
                    (sc1 & 0x0F0F0F0F) | (((sc2 >> 2) & 0x03030303) << 4),
                    ((sc0 >> 4) & 0x0F0F0F0F) | (((sc2 >> 4) & 0x03030303) << 4),
                    ((sc1 >> 4) & 0x0F0F0F0F) | (((sc2 >> 6) & 0x03030303) << 4),
                };
                var y_idx: usize = sb * 256;
                var is: usize = 0;
                var m_bit: u8 = 1;
                var q_off: usize = 0;
                for (0..2) |_| {
                    var shift: u3 = 0;
                    for (0..4) |_| {
                        const s0: i32 = @as(i32, @intCast((aux[is >> 2] >> @intCast((is & 3) * 8)) & 0xFF)) - 32;
                        is += 1;
                        const dl0 = d_all * @as(f32, @floatFromInt(s0));
                        for (0..16) |l| {
                            const qv: i32 = @as(i32, (qs[q_off + l] >> shift) & 3) - (if ((hm[l] & m_bit) != 0) @as(i32, 0) else @as(i32, 4));
                            out_f32[y_idx] = dl0 * @as(f32, @floatFromInt(qv));
                            y_idx += 1;
                        }
                        const s1: i32 = @as(i32, @intCast((aux[is >> 2] >> @intCast((is & 3) * 8)) & 0xFF)) - 32;
                        is += 1;
                        const dl1 = d_all * @as(f32, @floatFromInt(s1));
                        for (0..16) |l| {
                            const qv: i32 = @as(i32, (qs[q_off + 16 + l] >> shift) & 3) - (if ((hm[16 + l] & m_bit) != 0) @as(i32, 0) else @as(i32, 4));
                            out_f32[y_idx] = dl1 * @as(f32, @floatFromInt(qv));
                            y_idx += 1;
                        }
                        shift +%= 2;
                        m_bit <<= 1;
                    }
                    q_off += 32;
                }
            }
        },
        .gguf_q4_k => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 144 ..][0..144];
                const d = readF16AsF32(blk[0..2]);
                const dmin = readF16AsF32(blk[2..4]);
                const scales = blk[4..16];
                const qs = blk[16..144];
                var y_idx: usize = sb * 256;
                var q_off: usize = 0;
                var is: usize = 0;
                for (0..4) |_| {
                    const sm1 = getScaleMinK4(is + 0, scales);
                    const sm2 = getScaleMinK4(is + 1, scales);
                    const d1 = d * @as(f32, @floatFromInt(sm1.sc));
                    const m1 = dmin * @as(f32, @floatFromInt(sm1.min));
                    const d2 = d * @as(f32, @floatFromInt(sm2.sc));
                    const m2 = dmin * @as(f32, @floatFromInt(sm2.min));
                    for (0..32) |l| {
                        out_f32[y_idx] = d1 * @as(f32, @floatFromInt(qs[q_off + l] & 0xF)) - m1;
                        y_idx += 1;
                    }
                    for (0..32) |l| {
                        out_f32[y_idx] = d2 * @as(f32, @floatFromInt(qs[q_off + l] >> 4)) - m2;
                        y_idx += 1;
                    }
                    q_off += 32;
                    is += 2;
                }
            }
        },
        .gguf_q5_k => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 176 ..][0..176];
                const d = readF16AsF32(blk[0..2]);
                const dmin = readF16AsF32(blk[2..4]);
                const scales = blk[4..16];
                const qh = blk[16..48];
                const qs = blk[48..176];
                var y_idx: usize = sb * 256;
                var q_off: usize = 0;
                var is: usize = 0;
                var mask1: u8 = 1;
                var mask2: u8 = 2;
                for (0..4) |_| {
                    const sm1 = getScaleMinK4(is + 0, scales);
                    const sm2 = getScaleMinK4(is + 1, scales);
                    const d1 = d * @as(f32, @floatFromInt(sm1.sc));
                    const m1 = dmin * @as(f32, @floatFromInt(sm1.min));
                    const d2 = d * @as(f32, @floatFromInt(sm2.sc));
                    const m2 = dmin * @as(f32, @floatFromInt(sm2.min));
                    for (0..32) |l| {
                        const qv: u8 = (qs[q_off + l] & 0xF) + (if ((qh[l] & mask1) != 0) @as(u8, 16) else @as(u8, 0));
                        out_f32[y_idx] = d1 * @as(f32, @floatFromInt(qv)) - m1;
                        y_idx += 1;
                    }
                    for (0..32) |l| {
                        const qv: u8 = (qs[q_off + l] >> 4) + (if ((qh[l] & mask2) != 0) @as(u8, 16) else @as(u8, 0));
                        out_f32[y_idx] = d2 * @as(f32, @floatFromInt(qv)) - m2;
                        y_idx += 1;
                    }
                    q_off += 32;
                    is += 2;
                    mask1 <<= 2;
                    mask2 <<= 2;
                }
            }
        },
        .gguf_q6_k => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 210 ..][0..210];
                const d = readF16AsF32(blk[208..210]);
                for (0..2) |n_half| {
                    const ql = blk[n_half * 64 ..][0..64];
                    const qh = blk[128 + n_half * 32 ..][0..32];
                    const sc = blk[192 + n_half * 8 ..][0..8];
                    const base = sb * 256 + n_half * 128;
                    for (0..32) |l| {
                        const is = l / 16;
                        const q1: i32 = @as(i32, (ql[l + 0] & 0xF) | (((qh[l] >> 0) & 3) << 4)) - 32;
                        const q2: i32 = @as(i32, (ql[l + 32] & 0xF) | (((qh[l] >> 2) & 3) << 4)) - 32;
                        const q3: i32 = @as(i32, (ql[l + 0] >> 4) | (((qh[l] >> 4) & 3) << 4)) - 32;
                        const q4: i32 = @as(i32, (ql[l + 32] >> 4) | (((qh[l] >> 6) & 3) << 4)) - 32;
                        out_f32[base + l + 0] = d * @as(f32, @floatFromInt(@as(i8, @bitCast(sc[is + 0])))) * @as(f32, @floatFromInt(q1));
                        out_f32[base + l + 32] = d * @as(f32, @floatFromInt(@as(i8, @bitCast(sc[is + 2])))) * @as(f32, @floatFromInt(q2));
                        out_f32[base + l + 64] = d * @as(f32, @floatFromInt(@as(i8, @bitCast(sc[is + 4])))) * @as(f32, @floatFromInt(q3));
                        out_f32[base + l + 96] = d * @as(f32, @floatFromInt(@as(i8, @bitCast(sc[is + 6])))) * @as(f32, @floatFromInt(q4));
                    }
                }
            }
        },
        .gguf_iq1_s => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 50 ..][0..50];
                const d = readF16AsF32(blk[0..2]);
                const qs = blk[2..34];
                const qh_bytes = blk[34..50];
                var y_idx: usize = sb * 256;
                for (0..8) |ib| {
                    const qh = readU16(qh_bytes[ib * 2 ..][0..2]);
                    const dl = d * @as(f32, @floatFromInt(2 * ((qh >> 12) & 7) + 1));
                    const delta: f32 = if ((qh & 0x8000) != 0) -0.125 else 0.125;
                    for (0..4) |l| {
                        const idx: usize = qs[ib * 4 + l] | (((@as(usize, qh) >> @intCast(3 * l)) & 7) << 8);
                        const g = IQ1S_GRID_GPU[idx];
                        for (0..4) |j| {
                            const byte: u8 = @truncate(g >> @intCast(j * 8));
                            const v0: i32 = @as(i32, byte & 0xF) - 1;
                            const v1: i32 = @as(i32, byte >> 4) - 1;
                            out_f32[y_idx + j + 0] = dl * (@as(f32, @floatFromInt(v0)) + delta);
                            out_f32[y_idx + j + 4] = dl * (@as(f32, @floatFromInt(v1)) + delta);
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq1_m => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 56 ..][0..56];
                const qs = blk[0..32];
                const qh = blk[32..48];
                const sc_b = blk[48..56];
                const sc = [4]u16{
                    readU16(sc_b[0..2]),
                    readU16(sc_b[2..4]),
                    readU16(sc_b[4..6]),
                    readU16(sc_b[6..8]),
                };
                const d_u16: u16 = (sc[0] >> 12) | ((sc[1] >> 8) & 0x00F0) | ((sc[2] >> 4) & 0x0F00) | (sc[3] & 0xF000);
                const d: f32 = @floatCast(@as(f16, @bitCast(d_u16)));
                var y_idx: usize = sb * 256;
                for (0..8) |ib| {
                    const dl1 = d * @as(f32, @floatFromInt(2 * ((sc[ib / 2] >> @intCast(6 * (ib % 2) + 0)) & 7) + 1));
                    const dl2 = d * @as(f32, @floatFromInt(2 * ((sc[ib / 2] >> @intCast(6 * (ib % 2) + 3)) & 7) + 1));
                    const idx = [4]usize{
                        qs[ib * 4 + 0] | ((@as(usize, qh[ib * 2 + 0]) << 8) & 0x700),
                        qs[ib * 4 + 1] | ((@as(usize, qh[ib * 2 + 0]) << 4) & 0x700),
                        qs[ib * 4 + 2] | ((@as(usize, qh[ib * 2 + 1]) << 8) & 0x700),
                        qs[ib * 4 + 3] | ((@as(usize, qh[ib * 2 + 1]) << 4) & 0x700),
                    };
                    const delta = [4]f32{
                        if ((qh[ib * 2 + 0] & 0x08) != 0) -0.125 else 0.125,
                        if ((qh[ib * 2 + 0] & 0x80) != 0) -0.125 else 0.125,
                        if ((qh[ib * 2 + 1] & 0x08) != 0) -0.125 else 0.125,
                        if ((qh[ib * 2 + 1] & 0x80) != 0) -0.125 else 0.125,
                    };
                    for (0..4) |l| {
                        const dl = if (l < 2) dl1 else dl2;
                        const g = IQ1S_GRID_GPU[idx[l]];
                        for (0..4) |j| {
                            const byte: u8 = @truncate(g >> @intCast(j * 8));
                            const v0: i32 = @as(i32, byte & 0xF) - 1;
                            const v1: i32 = @as(i32, byte >> 4) - 1;
                            out_f32[y_idx + j + 0] = dl * (@as(f32, @floatFromInt(v0)) + delta[l]);
                            out_f32[y_idx + j + 4] = dl * (@as(f32, @floatFromInt(v1)) + delta[l]);
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq2_xxs => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 66 ..][0..66];
                const d = readF16AsF32(blk[0..2]);
                var y_idx: usize = sb * 256;
                for (0..8) |ib32| {
                    const aux0 = readU32(blk[2 + ib32 * 8 ..][0..4]);
                    const aux1 = readU32(blk[2 + ib32 * 8 + 4 ..][0..4]);
                    const db = d * (0.5 + @as(f32, @floatFromInt(aux1 >> 28))) * 0.25;
                    for (0..4) |l| {
                        const g_idx: usize = (aux0 >> @intCast(8 * l)) & 0xFF;
                        const sg = KSIGNS_IQ2XS[(aux1 >> @intCast(7 * l)) & 127];
                        const g = IQ2XXS_GRID[g_idx];
                        for (0..8) |j| {
                            const gv: u8 = @truncate(g >> @intCast(j * 8));
                            const sign: f32 = if ((sg & (@as(u8, 1) << @intCast(j))) != 0) -1.0 else 1.0;
                            out_f32[y_idx + j] = db * @as(f32, @floatFromInt(gv)) * sign;
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq2_xs => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 74 ..][0..74];
                const d = readF16AsF32(blk[0..2]);
                const qs = blk[2..66];
                const scales = blk[66..74];
                var y_idx: usize = sb * 256;
                for (0..8) |ib32| {
                    const db = [2]f32{
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] & 0xF))) * 0.25,
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] >> 4))) * 0.25,
                    };
                    for (0..4) |l| {
                        const q2 = readU16(qs[(ib32 * 4 + l) * 2 ..][0..2]);
                        const sg = KSIGNS_IQ2XS[q2 >> 9];
                        const g = IQ2XS_GRID[q2 & 511];
                        for (0..8) |j| {
                            const gv: u8 = @truncate(g >> @intCast(j * 8));
                            const sign: f32 = if ((sg & (@as(u8, 1) << @intCast(j))) != 0) -1.0 else 1.0;
                            out_f32[y_idx + j] = db[l / 2] * @as(f32, @floatFromInt(gv)) * sign;
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq2_s => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 82 ..][0..82];
                const d = readF16AsF32(blk[0..2]);
                const qs = blk[2..34];
                const signs = blk[34..66];
                const qh = blk[66..74];
                const scales = blk[74..82];
                var y_idx: usize = sb * 256;
                for (0..8) |ib32| {
                    const db = [2]f32{
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] & 0xF))) * 0.25,
                        d * (0.5 + @as(f32, @floatFromInt(scales[ib32] >> 4))) * 0.25,
                    };
                    for (0..4) |l| {
                        const dl = db[l / 2];
                        const idx: usize = qs[ib32 * 4 + l] | ((@as(usize, qh[ib32]) << @intCast(8 - 2 * l)) & 0x300);
                        const g = IQ2S_GRID[idx];
                        const sg = signs[ib32 * 4 + l];
                        for (0..8) |j| {
                            const gv: u8 = @truncate(g >> @intCast(j * 8));
                            const sign: f32 = if ((sg & (@as(u8, 1) << @intCast(j))) != 0) -1.0 else 1.0;
                            out_f32[y_idx + j] = dl * @as(f32, @floatFromInt(gv)) * sign;
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq3_xxs => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 98 ..][0..98];
                const d = readF16AsF32(blk[0..2]);
                const qs = blk[2..66];
                const sas = blk[66..98];
                var y_idx: usize = sb * 256;
                for (0..8) |ib32| {
                    const aux = readU32(sas[ib32 * 4 ..][0..4]);
                    const db = d * (0.5 + @as(f32, @floatFromInt(aux >> 28))) * 0.5;
                    for (0..4) |l| {
                        const sg = KSIGNS_IQ2XS[(aux >> @intCast(7 * l)) & 127];
                        const g1 = IQ3XXS_GRID[qs[ib32 * 8 + 2 * l + 0]];
                        const g2 = IQ3XXS_GRID[qs[ib32 * 8 + 2 * l + 1]];
                        for (0..4) |j| {
                            const v1: u8 = @truncate(g1 >> @intCast(j * 8));
                            const v2: u8 = @truncate(g2 >> @intCast(j * 8));
                            const s1: f32 = if ((sg & (@as(u8, 1) << @intCast(j + 0))) != 0) -1.0 else 1.0;
                            const s2: f32 = if ((sg & (@as(u8, 1) << @intCast(j + 4))) != 0) -1.0 else 1.0;
                            out_f32[y_idx + j + 0] = db * @as(f32, @floatFromInt(v1)) * s1;
                            out_f32[y_idx + j + 4] = db * @as(f32, @floatFromInt(v2)) * s2;
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq3_s => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 110 ..][0..110];
                const d = readF16AsF32(blk[0..2]);
                const qs = blk[2..66];
                const qh = blk[66..74];
                const signs = blk[74..106];
                const scales = blk[106..110];
                var y_idx: usize = sb * 256;
                for (0..8) |ib32| {
                    const db = d * @as(f32, @floatFromInt(1 + 2 * ((scales[ib32 / 2] >> @intCast(4 * (ib32 % 2))) & 0xF)));
                    for (0..4) |l| {
                        const idx1: usize = qs[ib32 * 8 + 2 * l + 0] | ((@as(usize, qh[ib32]) << @intCast(8 - 2 * l)) & 256);
                        const idx2: usize = qs[ib32 * 8 + 2 * l + 1] | ((@as(usize, qh[ib32]) << @intCast(7 - 2 * l)) & 256);
                        const g1 = IQ3S_GRID[idx1];
                        const g2 = IQ3S_GRID[idx2];
                        const sg = signs[ib32 * 4 + l];
                        for (0..4) |j| {
                            const v1: u8 = @truncate(g1 >> @intCast(j * 8));
                            const v2: u8 = @truncate(g2 >> @intCast(j * 8));
                            const s1: f32 = if ((sg & (@as(u8, 1) << @intCast(j + 0))) != 0) -1.0 else 1.0;
                            const s2: f32 = if ((sg & (@as(u8, 1) << @intCast(j + 4))) != 0) -1.0 else 1.0;
                            out_f32[y_idx + j + 0] = db * @as(f32, @floatFromInt(v1)) * s1;
                            out_f32[y_idx + j + 4] = db * @as(f32, @floatFromInt(v2)) * s2;
                        }
                        y_idx += 8;
                    }
                }
            }
        },
        .gguf_iq4_xs => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 136 ..][0..136];
                const d = readF16AsF32(blk[0..2]);
                const sh = readU16(blk[2..4]);
                const sl = blk[4..8];
                const qs = blk[8..136];
                for (0..8) |ib| {
                    const ls: i32 = @intCast(((sl[ib / 2] >> @intCast(4 * (ib % 2))) & 0xF) | (((sh >> @intCast(2 * ib)) & 3) << 4));
                    const dl = d * @as(f32, @floatFromInt(ls - 32));
                    const base = sb * 256 + ib * 32;
                    for (0..16) |j| {
                        out_f32[base + j + 0] = dl * @as(f32, @floatFromInt(KVALUES_IQ4NL[qs[ib * 16 + j] & 0xF]));
                        out_f32[base + j + 16] = dl * @as(f32, @floatFromInt(KVALUES_IQ4NL[qs[ib * 16 + j] >> 4]));
                    }
                }
            }
        },
        .gguf_tq1_0 => {
            const pow3 = [5]u8{ 1, 3, 9, 27, 81 };
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 54 ..][0..54];
                const qs = blk[0..48];
                const qh = blk[48..52];
                const d = readF16AsF32(blk[52..54]);
                var y_idx: usize = sb * 256;
                for (0..5) |n_idx| {
                    for (0..32) |m_idx| {
                        const q: u8 = qs[m_idx] *% pow3[n_idx];
                        const xi: i32 = @as(i32, (@as(u16, q) * 3) >> 8) - 1;
                        out_f32[y_idx] = @as(f32, @floatFromInt(xi)) * d;
                        y_idx += 1;
                    }
                }
                for (0..5) |n_idx| {
                    for (0..16) |m_idx| {
                        const q: u8 = qs[32 + m_idx] *% pow3[n_idx];
                        const xi: i32 = @as(i32, (@as(u16, q) * 3) >> 8) - 1;
                        out_f32[y_idx] = @as(f32, @floatFromInt(xi)) * d;
                        y_idx += 1;
                    }
                }
                for (0..4) |n_idx| {
                    for (0..4) |j| {
                        const q: u8 = qh[j] *% pow3[n_idx];
                        const xi: i32 = @as(i32, (@as(u16, q) * 3) >> 8) - 1;
                        out_f32[y_idx] = @as(f32, @floatFromInt(xi)) * d;
                        y_idx += 1;
                    }
                }
            }
        },
        .gguf_tq2_0 => {
            for (0..k / 256) |sb| {
                const blk = w_row[sb * 66 ..][0..66];
                const qs = blk[0..64];
                const d = readF16AsF32(blk[64..66]);
                var y_idx: usize = sb * 256;
                var j_off: usize = 0;
                while (j_off < 64) : (j_off += 32) {
                    for (0..4) |l| {
                        for (0..32) |m_idx| {
                            const q: i32 = @intCast((qs[j_off + m_idx] >> @intCast(l * 2)) & 3);
                            out_f32[y_idx] = @as(f32, @floatFromInt(q - 1)) * d;
                            y_idx += 1;
                        }
                    }
                }
            }
        },
        else => unreachable,
    }
}

/// Bit-exact `f32` CPU reference matrix multiply `Y[m, n] = sum_k X[m, k] * dequant(W[n, k]) (+ residual)`.
pub fn matmulCpuRef(
    allocator: std.mem.Allocator,
    dtype: DType,
    group_size: u16,
    x_f16: []const f16,
    qweight: []const u8,
    params: []const u8,
    residual_f16: ?[]const f16,
    out_f32: []f32,
    m: usize,
    n: usize,
    k: usize,
) (CpuRefError || std.mem.Allocator.Error)!void {
    if (m == 0) return error.ZeroDimension;
    try dtype.validateShape(n, k, group_size);
    if (x_f16.len < m * k or out_f32.len < m * n) return error.BufferTooSmall;
    if (residual_f16) |res| {
        if (res.len < m * n) return error.BufferTooSmall;
    }

    const row_buf = try allocator.alloc(f32, k);
    defer allocator.free(row_buf);

    for (0..n) |ni| {
        try dequantRowCpuRef(dtype, group_size, qweight, params, ni, n, k, row_buf);
        for (0..m) |mi| {
            const x_row = x_f16[mi * k ..][0..k];
            var acc: f32 = 0.0;
            for (0..k) |ki| {
                acc += @as(f32, @floatCast(x_row[ki])) * row_buf[ki];
            }
            if (residual_f16) |res| {
                acc += @as(f32, @floatCast(res[mi * n + ni]));
            }
            out_f32[mi * n + ni] = acc;
        }
    }
}

/// Bit-exact `f32` CPU reference for `G24` opt-in activation quantization emulation.
pub fn actQuantEmulateCpuRef(
    mode: ActQuantMode,
    x_in: []const f16,
    out_f16: []f16,
    m: usize,
    k: usize,
) CpuRefError!void {
    if (m == 0 or k == 0) return error.ZeroDimension;
    const req_align = mode.requiredKAlign();
    if ((k % req_align) != 0) return error.UnalignedK;
    if (x_in.len < m * k or out_f16.len < m * k) return error.BufferTooSmall;

    switch (mode) {
        .none => {
            @memcpy(out_f16[0 .. m * k], x_in[0 .. m * k]);
        },
        .mxfp8_g32 => {
            for (0..m) |row| {
                for (0..k / 32) |g| {
                    const base = row * k + g * 32;
                    var amax: f32 = 0.0;
                    for (0..32) |j| {
                        amax = @max(amax, @abs(@as(f32, @floatCast(x_in[base + j]))));
                    }
                    if (amax == 0.0) {
                        @memset(out_f16[base .. base + 32], @as(f16, 0.0));
                        continue;
                    }
                    const exp_i = std.math.clamp(@as(i32, @intFromFloat(@floor(@log2(amax)))) - 8 + 127, 0, 254);
                    const scale = ue8m0ToF32(@intCast(exp_i));
                    for (0..32) |j| {
                        const v: f32 = @floatCast(x_in[base + j]);
                        const q = f32ToE4m3(v / scale);
                        out_f16[base + j] = @floatCast(e4m3ToF32(q) * scale);
                    }
                }
            }
        },
        .fp8_g128 => {
            for (0..m) |row| {
                for (0..k / 128) |g| {
                    const base = row * k + g * 128;
                    var amax: f32 = 0.0;
                    for (0..128) |j| {
                        amax = @max(amax, @abs(@as(f32, @floatCast(x_in[base + j]))));
                    }
                    if (amax == 0.0) {
                        @memset(out_f16[base .. base + 128], @as(f16, 0.0));
                        continue;
                    }
                    const scale = amax / 448.0;
                    for (0..128) |j| {
                        const v: f32 = @floatCast(x_in[base + j]);
                        const q = f32ToE4m3(v / scale);
                        out_f16[base + j] = @floatCast(e4m3ToF32(q) * scale);
                    }
                }
            }
        },
        .nvfp4_g16, .nvfp4_fouroversix_mae => {
            const use_4o6 = (mode == .nvfp4_fouroversix_mae);
            for (0..m) |row| {
                const row_base = row * k;
                var row_amax: f32 = 0.0;
                for (0..k) |c| {
                    row_amax = @max(row_amax, @abs(@as(f32, @floatCast(x_in[row_base + c]))));
                }
                const outer: f32 = if (row_amax > 0.0) row_amax / 2688.0 else 1.0;

                for (0..k / 16) |g| {
                    const base = row_base + g * 16;
                    var b_amax: f32 = 0.0;
                    for (0..16) |j| {
                        b_amax = @max(b_amax, @abs(@as(f32, @floatCast(x_in[base + j]))));
                    }
                    const d6_b: u8 = if (b_amax > 0.0) f32ToE4m3(b_amax / (6.0 * outer)) else 0;
                    const s6 = e4m3ScaleToF32(d6_b) * outer;
                    var x6: [16]f32 = undefined;
                    var mae6: f32 = 0.0;
                    for (0..16) |j| {
                        const v: f32 = @floatCast(x_in[base + j]);
                        x6[j] = if (s6 > 0.0) e2m1ToF32(f32ToE2m1(v / s6)) * s6 else 0.0;
                        mae6 += @abs(x6[j] - v);
                    }
                    if (!use_4o6) {
                        for (0..16) |j| out_f16[base + j] = @floatCast(x6[j]);
                        continue;
                    }
                    const d4_b: u8 = if (b_amax > 0.0) f32ToE4m3(b_amax / (4.0 * outer)) else 0;
                    const s4 = e4m3ScaleToF32(d4_b) * outer;
                    var x4: [16]f32 = undefined;
                    var mae4: f32 = 0.0;
                    for (0..16) |j| {
                        const v: f32 = @floatCast(x_in[base + j]);
                        x4[j] = if (s4 > 0.0) e2m1ToF32(f32ToE2m1(v / s4)) * s4 else 0.0;
                        mae4 += @abs(x4[j] - v);
                    }
                    const chosen = if (mae4 < mae6) &x4 else &x6;
                    for (0..16) |j| out_f16[base + j] = @floatCast(chosen[j]);
                }
            }
        },
    }
}

