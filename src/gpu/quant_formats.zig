    if (@sizeOf(ScaleBias) != 4) @compileError("ScaleBias must be 4 bytes");
}

pub const FormatSpec = struct {
    dtype: DType,
    group_size: u16 = 0,

    pub fn normalized(dtype: DType, group_size: u16) FormatSpec {
        return .{
            .dtype = dtype,
            .group_size = dtype.effectiveGroupSize(group_size),
        };
    }
};

