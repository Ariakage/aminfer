pub const DType = enum(u8) {
    q4_affine = 2,
    q3_affine = 3,
    q2_affine = 6,
    q5_affine = 7,
    q6_affine = 8,
    q8_affine = 9,
    fp8_e4m3_block = 10,
    fp8_e4m3_row = 11,
    fp8_e4m3_tensor = 12,
    mxfp8_g32 = 13,
    nvfp4_g16 = 14,
    gguf_q4_0 = 15,
    gguf_q4_1 = 16,
    gguf_q5_0 = 17,
    gguf_q5_1 = 18,
    gguf_q8_0 = 19,
    gguf_q2_k = 20,
    gguf_q3_k = 21,
    gguf_q4_k = 22,
    gguf_q5_k = 23,
    gguf_q6_k = 24,
    gguf_iq1_s = 25,
    gguf_iq1_m = 26,
    gguf_iq2_xxs = 27,
    gguf_iq2_xs = 28,
    gguf_iq2_s = 29,
    gguf_iq3_xxs = 30,
    gguf_iq3_s = 31,
    gguf_iq4_nl = 32,
    gguf_iq4_xs = 33,
    gguf_tq1_0 = 34,
    gguf_tq2_0 = 35,
    gguf_mxfp4 = 36,
    gguf_q2_0 = 37,

    pub fn isAffine(self: DType) bool {
        return switch (self) {
            .q2_affine, .q3_affine, .q4_affine, .q5_affine, .q6_affine, .q8_affine => true,
            else => false,
        };
    }

    pub fn affineBits(self: DType) ?u8 {
        return switch (self) {
            .q2_affine => 2,
            .q3_affine => 3,
            .q4_affine => 4,
            .q5_affine => 5,
            .q6_affine => 6,
            .q8_affine => 8,
            else => null,
        };
    }

    pub fn isFpFamily(self: DType) bool {
        return switch (self) {
            .fp8_e4m3_block, .fp8_e4m3_row, .fp8_e4m3_tensor, .mxfp8_g32, .nvfp4_g16 => true,
            else => false,
        };
    }

    pub fn isGgufBlk(self: DType) bool {
        return switch (self) {
            .gguf_q4_0,
            .gguf_q4_1,
            .gguf_q5_0,
            .gguf_q5_1,
            .gguf_q8_0,
            .gguf_iq4_nl,
            .gguf_mxfp4,
            .gguf_q2_0,
            => true,
            else => false,
        };
    }

    pub fn isGgufK(self: DType) bool {
        return switch (self) {
            .gguf_q2_k,
            .gguf_q3_k,
            .gguf_q4_k,
            .gguf_q5_k,
            .gguf_q6_k,
            .gguf_iq4_xs,
            .gguf_tq1_0,
            .gguf_tq2_0,
            => true,
            else => false,
        };
    }

    pub fn needsCodebook(self: DType) bool {
        return switch (self) {
            .gguf_iq1_s,
            .gguf_iq1_m,
            .gguf_iq2_xxs,
            .gguf_iq2_xs,
            .gguf_iq2_s,
            .gguf_iq3_xxs,
            .gguf_iq3_s,
            => true,
            else => false,
        };
    }

    pub fn effectiveGroupSize(self: DType, requested_gs: u16) u16 {
        return switch (self) {
            .q2_affine, .q3_affine, .q4_affine, .q5_affine, .q6_affine, .q8_affine => if (requested_gs == 0) 64 else requested_gs,
            .fp8_e4m3_block => 128,
            .fp8_e4m3_row, .fp8_e4m3_tensor => 0,
            .mxfp8_g32 => 32,
            .nvfp4_g16 => 16,
            .gguf_q4_0, .gguf_q4_1, .gguf_q5_0, .gguf_q5_1, .gguf_q8_0, .gguf_iq4_nl, .gguf_mxfp4 => 32,
            .gguf_q2_0 => 64,
            .gguf_q2_k,
            .gguf_q3_k,
            .gguf_q4_k,
            .gguf_q5_k,
            .gguf_q6_k,
            .gguf_iq1_s,
            .gguf_iq1_m,
            .gguf_iq2_xxs,
            .gguf_iq2_xs,
            .gguf_iq2_s,
            .gguf_iq3_xxs,
            .gguf_iq3_s,
            .gguf_iq4_xs,
            .gguf_tq1_0,
            .gguf_tq2_0,
            => 256,
        };
    }

    pub fn blockElems(self: DType, group_size: u16) u32 {
        return switch (self) {
            .fp8_e4m3_block, .fp8_e4m3_row, .fp8_e4m3_tensor => 1,
            else => self.effectiveGroupSize(group_size),
        };
    }

    pub fn blockBytes(self: DType, group_size: u16) u32 {
        return switch (self) {
            .q2_affine, .q3_affine, .q4_affine, .q5_affine, .q6_affine, .q8_affine => blk: {
                const bits: u32 = self.affineBits().?;
                const gs: u32 = self.effectiveGroupSize(group_size);
                break :blk (gs * bits) / 8;
            },
            .fp8_e4m3_block, .fp8_e4m3_row, .fp8_e4m3_tensor, .mxfp8_g32 => switch (self) {
                .mxfp8_g32 => 32,
                else => 1,
            },
            .nvfp4_g16 => 8,
            .gguf_q4_0 => 18,
            .gguf_q4_1 => 20,
            .gguf_q5_0 => 22,
            .gguf_q5_1 => 24,
            .gguf_q8_0 => 34,
            .gguf_q2_k => 84,
            .gguf_q3_k => 110,
            .gguf_q4_k => 144,
            .gguf_q5_k => 176,
            .gguf_q6_k => 210,
            .gguf_iq1_s => 50,
            .gguf_iq1_m => 56,
            .gguf_iq2_xxs => 66,
            .gguf_iq2_xs => 74,
            .gguf_iq2_s => 82,
            .gguf_iq3_xxs => 98,
            .gguf_iq3_s => 110,
            .gguf_iq4_nl => 18,
            .gguf_iq4_xs => 136,
            .gguf_tq1_0 => 54,
            .gguf_tq2_0 => 66,
            .gguf_mxfp4 => 17,
            .gguf_q2_0 => 18,
        };
    }

    pub fn validateShape(self: DType, n: usize, k: usize, group_size: u16) ShapeError!void {
        if (n == 0 or k == 0) return error.ZeroDimension;
        if (self.isAffine()) {
            const eff_gs = self.effectiveGroupSize(group_size);
            if (eff_gs != 32 and eff_gs != 64 and eff_gs != 128) return error.InvalidGroupSize;
            if (k % eff_gs != 0) return error.UnalignedK;
            return;
        }
        const blk_elems = self.blockElems(group_size);
        if (blk_elems > 1 and (k % blk_elems) != 0) return error.UnalignedK;
    }

    pub fn groupsPerRow(self: DType, k: usize, group_size: u16) ShapeError!usize {
        if (k == 0) return error.ZeroDimension;
        if (self.isAffine()) {
            const eff_gs = self.effectiveGroupSize(group_size);
            if (eff_gs != 32 and eff_gs != 64 and eff_gs != 128) return error.InvalidGroupSize;
            if (k % eff_gs != 0) return error.UnalignedK;
            return k / eff_gs;
        }
        return switch (self) {
            .fp8_e4m3_block => (k + 127) / 128,
            .fp8_e4m3_row, .fp8_e4m3_tensor => 1,
            else => blk: {
                const elems = self.blockElems(group_size);
                if (k % elems != 0) return error.UnalignedK;
                break :blk k / elems;
            },
        };
    }

    pub fn rowWeightBytes(self: DType, k: usize, group_size: u16) ShapeError!usize {
        if (k == 0) return error.ZeroDimension;
        if (self == .fp8_e4m3_block or self == .fp8_e4m3_row or self == .fp8_e4m3_tensor) {
            return k;
        }
        const grps = try self.groupsPerRow(k, group_size);
        const bb = self.blockBytes(group_size);
        return std.math.mul(usize, grps, bb) catch return error.Overflow;
    }

    pub fn packedWeightBytes(self: DType, n: usize, k: usize, group_size: u16) ShapeError!usize {
        if (n == 0) return error.ZeroDimension;
        const rb = try self.rowWeightBytes(k, group_size);
        return std.math.mul(usize, n, rb) catch return error.Overflow;
    }

    pub fn nvfp4OuterScaleOffset(n: usize, k: usize) ShapeError!usize {
        if (n == 0 or k == 0) return error.ZeroDimension;
        if (k % 16 != 0) return error.UnalignedK;
        const grps = k / 16;
        const total = std.math.mul(usize, n, grps) catch return error.Overflow;
        return align4(total);
    }

    pub fn paramsBytes(self: DType, n: usize, k: usize, group_size: u16) ShapeError!usize {
        try self.validateShape(n, k, group_size);
        return switch (self) {
            .q2_affine, .q3_affine, .q4_affine, .q5_affine, .q6_affine, .q8_affine => blk: {
                const grps = try self.groupsPerRow(k, group_size);
                const total = std.math.mul(usize, n, grps) catch return error.Overflow;
                break :blk std.math.mul(usize, total, @sizeOf(ScaleBias)) catch return error.Overflow;
            },
            .fp8_e4m3_block => blk: {
                const nb = (n + 127) / 128;
                const kb = (k + 127) / 128;
                const total = std.math.mul(usize, nb, kb) catch return error.Overflow;
                break :blk std.math.mul(usize, total, @sizeOf(f32)) catch return error.Overflow;
            },
            .fp8_e4m3_row => std.math.mul(usize, n, @sizeOf(f32)) catch return error.Overflow,
            .fp8_e4m3_tensor => @sizeOf(f32),
            .mxfp8_g32 => std.math.mul(usize, n, k / 32) catch return error.Overflow,
            .nvfp4_g16 => blk: {
                const off = try nvfp4OuterScaleOffset(n, k);
                break :blk std.math.add(usize, off, @sizeOf(f32)) catch return error.Overflow;
            },
            else => 0,
        };
    }

    pub fn codebookOffset(self: DType) usize {
        return switch (self) {
            .gguf_iq1_s, .gguf_iq1_m => CODEBOOK_OFF_IQ1S,
            .gguf_iq2_xxs => CODEBOOK_OFF_IQ2XXS,
            .gguf_iq2_xs => CODEBOOK_OFF_IQ2XS,
            .gguf_iq2_s => CODEBOOK_OFF_IQ2S,
            .gguf_iq3_xxs => CODEBOOK_OFF_IQ3XXS,
            .gguf_iq3_s => CODEBOOK_OFF_IQ3S,
            else => 0,
        };
    }
};

/// Opt-in activation quantization emulation mode (`G24`).
pub const ActQuantMode = enum(u8) {
    none = 0,
    mxfp8_g32 = 1,
    fp8_g128 = 2,
    nvfp4_g16 = 3,
    nvfp4_fouroversix_mae = 4,

    pub fn requiredKAlign(self: ActQuantMode) u32 {
        return switch (self) {
            .none => 1,
            .mxfp8_g32 => 32,
            .fp8_g128 => 128,
            .nvfp4_g16, .nvfp4_fouroversix_mae => 16,
        };
    }
};

