    /// Encodes `G24` opt-in activation quant-dequant emulation.
    /// Completely bypassed (`0` dispatches, `0` barriers) when `mode == .none`.
    pub fn encodeActQuantEmulate(
        self: *const QuantFormatPipelines,
        frame: *metal.Compute.Frame,
        mode: ActQuantMode,
        args: ActQuantArgs,
        insert_barrier_before: bool,
    ) EncodeError!void {
        if (mode == .none) return;
        if (args.m == 0 or args.k == 0) return error.ZeroDimension;
        if ((args.k % mode.requiredKAlign()) != 0) return error.UnalignedK;
        const pipe = self.act_quant[@backingInt(mode) - 1] orelse return error.PipelineNotInitialized;
        const p = ActQuantParams{
            .m = args.m,
            .k = args.k,
            .mode = @backingInt(mode),
        };
        const groups_x: u64 = switch (mode) {
            .none => unreachable,
            .mxfp8_g32 => ((@as(u64, args.k) / 32) + 3) / 4,
            .fp8_g128 => @as(u64, args.k) / 128,
            .nvfp4_g16, .nvfp4_fouroversix_mae => 1,
        };
        try frame.encodeThreadgroups(
            pipe,
            &.{ args.x_in, args.x_out },
            std.mem.asBytes(&p),
            .{ groups_x, args.m, 1 },
            .{ 128, 1, 1 },
            insert_barrier_before,
        );
    }
