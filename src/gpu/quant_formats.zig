fn kernelNameFor(dtype: DType, kind: KernelKind) [:0]const u8 {
    if (dtype.isAffine()) {
        return switch (kind) {
            .gemv => "ami_qf_affine_gemv",
            .gemv_batch => "ami_qf_affine_gemv_batch",
            .dequant_tile_f16 => "ami_qf_affine_dequant_tile_f16",
            .moe_gate_up => "ami_qf_affine_moe_gate_up_swiglu",
            .moe_down => "ami_qf_affine_moe_down_proj",
        };
    }
    if (dtype.isFpFamily()) {
        return switch (kind) {
            .gemv => "ami_qf_fp_gemv",
            .gemv_batch => "ami_qf_fp_gemv_batch",
            .dequant_tile_f16 => "ami_qf_fp_dequant_tile_f16",
            .moe_gate_up => "ami_qf_fp_moe_gate_up_swiglu",
            .moe_down => "ami_qf_fp_moe_down_proj",
        };
    }
    if (dtype.isGgufBlk()) {
        return switch (kind) {
            .gemv => "ami_qf_gguf_blk_gemv",
            .gemv_batch => "ami_qf_gguf_blk_gemv_batch",
            .dequant_tile_f16 => "ami_qf_gguf_blk_dequant_tile_f16",
            .moe_gate_up => "ami_qf_gguf_blk_moe_gate_up_swiglu",
            .moe_down => "ami_qf_gguf_blk_moe_down_proj",
        };
    }
    if (dtype.isGgufK()) {
        return switch (kind) {
            .gemv => "ami_qf_gguf_k_gemv",
            .gemv_batch => "ami_qf_gguf_k_gemv_batch",
            .dequant_tile_f16 => "ami_qf_gguf_k_dequant_tile_f16",
            .moe_gate_up => "ami_qf_gguf_k_moe_gate_up_swiglu",
            .moe_down => "ami_qf_gguf_k_moe_down_proj",
        };
    }
    return switch (kind) {
        .gemv => "ami_qf_iq_gemv",
        .gemv_batch => "ami_qf_iq_gemv_batch",
        .dequant_tile_f16 => "ami_qf_iq_dequant_tile_f16",
        .moe_gate_up => "ami_qf_iq_moe_gate_up_swiglu",
        .moe_down => "ami_qf_iq_moe_down_proj",
    };
}

fn slotIndex(dtype: DType, group_size: u16) ?usize {
    const eff_gs = dtype.effectiveGroupSize(group_size);
    for (ALL_FORMAT_SPECS, 0..) |spec, i| {
        if (spec.dtype == dtype and spec.group_size == eff_gs) return i;
    }
    return null;
}

fn fillCodebookRegion(bytes: []u8) void {
    @memset(bytes, 0);
    // IQ1_S / IQ1_M: 2048 * u32 = 8,192 B
    const iq1_src = std.mem.sliceAsBytes(&IQ1S_GRID_GPU);
    @memcpy(bytes[CODEBOOK_OFF_IQ1S..][0..iq1_src.len], iq1_src);

    // IQ2_XXS: 256 * u64 + 128 * u8 signs
    const iq2xxs_src = std.mem.sliceAsBytes(&IQ2XXS_GRID);
    @memcpy(bytes[CODEBOOK_OFF_IQ2XXS..][0..iq2xxs_src.len], iq2xxs_src);
    @memcpy(bytes[CODEBOOK_OFF_IQ2XXS + iq2xxs_src.len ..][0..KSIGNS_IQ2XS.len], &KSIGNS_IQ2XS);

    // IQ2_XS: 512 * u64 + 128 * u8 signs
    const iq2xs_src = std.mem.sliceAsBytes(&IQ2XS_GRID);
    @memcpy(bytes[CODEBOOK_OFF_IQ2XS..][0..iq2xs_src.len], iq2xs_src);
    @memcpy(bytes[CODEBOOK_OFF_IQ2XS + iq2xs_src.len ..][0..KSIGNS_IQ2XS.len], &KSIGNS_IQ2XS);

    // IQ2_S: 1024 * u64
    const iq2s_src = std.mem.sliceAsBytes(&IQ2S_GRID);
    @memcpy(bytes[CODEBOOK_OFF_IQ2S..][0..iq2s_src.len], iq2s_src);

    // IQ3_XXS: 256 * u32 + 128 * u8 signs
    const iq3xxs_src = std.mem.sliceAsBytes(&IQ3XXS_GRID);
    @memcpy(bytes[CODEBOOK_OFF_IQ3XXS..][0..iq3xxs_src.len], iq3xxs_src);
    @memcpy(bytes[CODEBOOK_OFF_IQ3XXS + iq3xxs_src.len ..][0..KSIGNS_IQ2XS.len], &KSIGNS_IQ2XS);

    // IQ3_S: 512 * u32
    const iq3s_src = std.mem.sliceAsBytes(&IQ3S_GRID);
    @memcpy(bytes[CODEBOOK_OFF_IQ3S..][0..iq3s_src.len], iq3s_src);
}

/// Preallocated Metal 4 pipeline table & wired IQ codebook buffer for G23 + G24.
pub const QuantFormatPipelines = struct {
    slots: [ALL_FORMAT_SPECS.len]?FormatPipelineSet = @splat(null),
    act_quant: [4]?metal.Pipeline = @splat(null),
    codebook_region: page.WiredRegion,
    codebook_buf: metal.Buffer,

    pub fn init(device: metal.Device, library: metal.Library) InitError!QuantFormatPipelines {
        return initWithOptions(device, library, .{});
    }

    pub fn initWithOptions(device: metal.Device, library: metal.Library, opts: InitOptions) InitError!QuantFormatPipelines {
        const region = try page.WiredRegion.init(CODEBOOK_TOTAL_BYTES);
        errdefer region.deinit();
        fillCodebookRegion(region.bytes);

        const cb_buf = try metal.Buffer.wrap(device, region.bytes);
        errdefer cb_buf.close();

        var self = QuantFormatPipelines{
            .codebook_region = region,
            .codebook_buf = cb_buf,
        };
        errdefer self.closePipelinesOnly();

        const target_specs = opts.specs orelse &ALL_FORMAT_SPECS;
        for (target_specs) |raw_spec| {
            const spec = FormatSpec.normalized(raw_spec.dtype, raw_spec.group_size);
            const idx = slotIndex(spec.dtype, spec.group_size) orelse return error.InvalidArgument;
            if (self.slots[idx] != null) continue;

            const fcs = [_]metal.FnConstant{
                .{ .index = 0, .value = .{ .u32 = @backingInt(spec.dtype) } },
                .{ .index = 1, .value = .{ .u32 = spec.group_size } },
                .{ .index = 2, .value = .{ .bool = false } },
            };

            const gemv = try metal.Pipeline.initSpecialized(device, library, kernelNameFor(spec.dtype, .gemv), &fcs);
            errdefer gemv.close();
            const gemv_batch = try metal.Pipeline.initSpecialized(device, library, kernelNameFor(spec.dtype, .gemv_batch), &fcs);
            errdefer gemv_batch.close();
            const tile = try metal.Pipeline.initSpecialized(device, library, kernelNameFor(spec.dtype, .dequant_tile_f16), &fcs);
            errdefer tile.close();

            var moe_gu: ?metal.Pipeline = null;
            errdefer if (moe_gu) |p| p.close();
            var moe_dn: ?metal.Pipeline = null;
            errdefer if (moe_dn) |p| p.close();
            if (opts.include_moe) {
                moe_gu = try metal.Pipeline.initSpecialized(device, library, kernelNameFor(spec.dtype, .moe_gate_up), &fcs);
                moe_dn = try metal.Pipeline.initSpecialized(device, library, kernelNameFor(spec.dtype, .moe_down), &fcs);
            }

            self.slots[idx] = .{
                .gemv = gemv,
                .gemv_batch = gemv_batch,
                .dequant_tile_f16 = tile,
                .moe_gate_up = moe_gu,
                .moe_down = moe_dn,
            };
        }

        if (opts.include_act_quant) {
            inline for (1..5) |mode_val| {
                self.act_quant[mode_val - 1] = try metal.Pipeline.initSpecialized(
                    device,
                    library,
                    "ami_act_quant_emulate_f16",
                    &.{.{ .index = 3, .value = .{ .u32 = @intCast(mode_val) } }},
                );
            }
        }

        return self;
    }

    fn closePipelinesOnly(self: *const QuantFormatPipelines) void {
        for (self.act_quant) |maybe_p| {
            if (maybe_p) |p| p.close();
        }
        for (self.slots) |maybe_set| {
            if (maybe_set) |set| set.close();
        }
    }

    pub fn close(self: *const QuantFormatPipelines) void {
        self.closePipelinesOnly();
        self.codebook_buf.close();
        self.codebook_region.deinit();
    }

    pub fn makeResident(self: *const QuantFormatPipelines, compute: metal.Compute) metal.Error!void {
        try compute.makeResident(&.{self.codebook_buf});
    }

    pub fn pipelineFor(self: *const QuantFormatPipelines, dtype: DType, group_size: u16, kind: KernelKind) ?metal.Pipeline {
        const idx = slotIndex(dtype, group_size) orelse return null;
        const set = self.slots[idx] orelse return null;
        return switch (kind) {
            .gemv => set.gemv,
            .gemv_batch => set.gemv_batch,
            .dequant_tile_f16 => set.dequant_tile_f16,
            .moe_gate_up => set.moe_gate_up,
            .moe_down => set.moe_down,
        };
    }

    fn buildParams(
        dtype: DType,
        group_size: u16,
        m: u32,
        n: u32,
        k: u32,
        has_residual: bool,
        tensor_scale_per_row: bool,
        nvfp4_outer_scale: ?f32,
    ) ShapeError!QuantFormatParams {
        try dtype.validateShape(n, k, group_size);
        const grps = try dtype.groupsPerRow(k, group_size);
        const rb = try dtype.rowWeightBytes(k, group_size);
        const scale_stride: u32 = switch (dtype) {
            .fp8_e4m3_block => @intCast((@as(usize, k) + 127) / 128),
            .fp8_e4m3_tensor => if (tensor_scale_per_row) 1 else 0,
            else => 0,
        };
        var outer_off: u32 = 0xFFFFFFFF;
        var outer_val: f32 = 1.0;
        if (dtype == .nvfp4_g16) {
            if (nvfp4_outer_scale) |ov| {
                outer_val = ov;
            } else {
                outer_off = @intCast(try DType.nvfp4OuterScaleOffset(n, k));
            }
        }
        return .{
            .m = m,
            .n = n,
            .k = k,
            .num_groups = @intCast(grps),
            .row_bytes = @intCast(rb),
            .scale_stride = scale_stride,
            .outer_scale_offset = outer_off,
            .outer_scale = outer_val,
            .has_residual = if (has_residual) 1 else 0,
        };
    }

    pub fn encodeGemv(
        self: *const QuantFormatPipelines,
        frame: *metal.Compute.Frame,
        dtype: DType,
        group_size: u16,
        args: GemvArgs,
        insert_barrier_before: bool,
    ) EncodeError!void {
        const pipe = self.pipelineFor(dtype, group_size, .gemv) orelse return error.PipelineNotInitialized;
        const p = try buildParams(
            dtype,
            group_size,
            1,
            args.n,
            args.k,
            args.residual != null,
            args.tensor_scale_per_row,
            args.nvfp4_outer_scale,
        );
        const scales_b = args.params orelse args.qweight;
        const res_b = args.residual orelse args.y;
        const groups_x: u64 = (@as(u64, args.n) + 15) / 16;

        if (dtype.needsCodebook()) {
            const cb = metal.BufferBinding{ .buffer = self.codebook_buf, .offset = dtype.codebookOffset() };
            try frame.encodeThreadgroups(
                pipe,
                &.{ args.x, args.qweight, scales_b, args.y, res_b, cb },
                std.mem.asBytes(&p),
                .{ groups_x, 1, 1 },
                .{ 128, 1, 1 },
                insert_barrier_before,
            );
        } else {
            try frame.encodeThreadgroups(
                pipe,
                &.{ args.x, args.qweight, scales_b, args.y, res_b },
                std.mem.asBytes(&p),
                .{ groups_x, 1, 1 },
                .{ 128, 1, 1 },
                insert_barrier_before,
            );
        }
    }

    pub fn encodeGemvBatch(
        self: *const QuantFormatPipelines,
        frame: *metal.Compute.Frame,
        dtype: DType,
        group_size: u16,
        args: GemmBatchArgs,
        insert_barrier_before: bool,
    ) EncodeError!void {
        if (args.m == 0) return error.ZeroDimension;
        const pipe = self.pipelineFor(dtype, group_size, .gemv_batch) orelse return error.PipelineNotInitialized;
        const p = try buildParams(
            dtype,
            group_size,
            args.m,
            args.n,
            args.k,
            args.residual != null,
            args.tensor_scale_per_row,
            args.nvfp4_outer_scale,
        );
        const scales_b = args.params orelse args.qweight;
        const res_b = args.residual orelse args.y;
        const groups_x: u64 = (@as(u64, args.n) + 7) / 8;
        const groups_y: u64 = (@as(u64, args.m) + 7) / 8;

        if (dtype.needsCodebook()) {
            const cb = metal.BufferBinding{ .buffer = self.codebook_buf, .offset = dtype.codebookOffset() };
            try frame.encodeThreadgroups(
                pipe,
                &.{ args.x, args.qweight, scales_b, args.y, res_b, cb },
                std.mem.asBytes(&p),
                .{ groups_x, groups_y, 1 },
                .{ 128, 1, 1 },
                insert_barrier_before,
            );
        } else {
            try frame.encodeThreadgroups(
                pipe,
                &.{ args.x, args.qweight, scales_b, args.y, res_b },
                std.mem.asBytes(&p),
                .{ groups_x, groups_y, 1 },
                .{ 128, 1, 1 },
                insert_barrier_before,
            );
        }
    }

    pub fn encodeDequantTileF16(
        self: *const QuantFormatPipelines,
        frame: *metal.Compute.Frame,
        dtype: DType,
        group_size: u16,
        args: TileDequantArgs,
        insert_barrier_before: bool,
    ) EncodeError!void {
        if (args.tile_n == 0 or args.tile_k == 0) return error.ZeroDimension;
        if (@as(u64, args.tile_n_start) + args.tile_n > args.n_total or
            @as(u64, args.tile_k_start) + args.tile_k > args.k_total)
        {
            return error.InvalidArgument;
        }
        const blk_elems = dtype.blockElems(group_size);
        if (blk_elems > 1 and ((args.tile_k_start % blk_elems) != 0 or (args.tile_k % blk_elems) != 0)) {
            return error.UnalignedK;
        }
        const pipe = self.pipelineFor(dtype, group_size, .dequant_tile_f16) orelse return error.PipelineNotInitialized;
        var p = try buildParams(
            dtype,
            group_size,
            1,
            args.n_total,
            args.k_total,
            false,
            args.tensor_scale_per_row,
            args.nvfp4_outer_scale,
        );
        p.tile_n_start = args.tile_n_start;
        p.tile_k_start = args.tile_k_start;
        p.tile_n = args.tile_n;
        p.tile_k = args.tile_k;
        p.dst_stride = if (args.dst_stride != 0) args.dst_stride else args.tile_k;
        if (p.dst_stride < args.tile_k) return error.InvalidArgument;

        const scales_b = args.params orelse args.qweight;
        const groups_x: u64 = (@as(u64, args.tile_k) + 255) / 256;
        const groups_y: u64 = (@as(u64, args.tile_n) + 3) / 4;

        if (dtype.needsCodebook()) {
            const cb = metal.BufferBinding{ .buffer = self.codebook_buf, .offset = dtype.codebookOffset() };
            try frame.encodeThreadgroups(
                pipe,
                &.{ args.qweight, scales_b, args.dst_f16, cb },
                std.mem.asBytes(&p),
                .{ groups_x, groups_y, 1 },
                .{ 128, 1, 1 },
                insert_barrier_before,
            );
        } else {
            try frame.encodeThreadgroups(
                pipe,
                &.{ args.qweight, scales_b, args.dst_f16 },
                std.mem.asBytes(&p),
                .{ groups_x, groups_y, 1 },
                .{ 128, 1, 1 },
                insert_barrier_before,
            );
        }
    }

